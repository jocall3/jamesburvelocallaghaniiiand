import { SubscriptionRepository } from '../data/SubscriptionRepository';
import { StripeService } from './StripeService';
import { Subscription, SubscriptionStatus, SubscriptionPlan, User } from '../types';
import { v4 as uuidv4 } from 'uuid';
import { logger } from '../utils/logger';

/**
 * Service responsible for managing user subscriptions, handling interactions
 * with the data layer (SubscriptionRepository) and external payment processors (StripeService).
 * Implements business logic for subscription lifecycle management.
 */
export class CA_SubscriptionService {
    private subscriptionRepo: SubscriptionRepository;
    private stripeService: StripeService;

    constructor(
        subscriptionRepo: SubscriptionRepository,
        stripeService: StripeService
    ) {
        this.subscriptionRepo = subscriptionRepo;
        this.stripeService = stripeService;
    }

    /**
     * AE1: Creates a new subscription record in the database for a user.
     * @param userId The ID of the user.
     * @param planId The ID of the subscription plan.
     * @returns The newly created subscription object.
     */
    public async createSubscription(userId: string, planId: string): Promise<Subscription> {
        logger.info(`Attempting to create new subscription for User ${userId} with Plan ${planId}`);
        
        const newSubscription: Subscription = {
            id: uuidv4(),
            userId: userId,
            planId: planId,
            status: SubscriptionStatus.TRIALING, // Default status upon creation before payment confirmation
            startDate: new Date(),
            endDate: new Date(Date.now() + 7 * 24 * 60 * 60 * 1000), // Default 7-day trial
            createdAt: new Date(),
            updatedAt: new Date(),
            stripeSubscriptionId: null,
            cancellationDate: null,
        };

        const createdSub = await this.subscriptionRepo.save(newSubscription);
        logger.info(`Subscription ${createdSub.id} created successfully.`);
        return createdSub;
    }

    /**
     * AE2: Retrieves a subscription by its unique ID.
     * @param subscriptionId The ID of the subscription.
     * @returns The subscription object or null if not found.
     */
    public async getSubscriptionById(subscriptionId: string): Promise<Subscription | null> {
        logger.debug(`Fetching subscription by ID: ${subscriptionId}`);
        return this.subscriptionRepo.findById(subscriptionId);
    }

    /**
     * AE3: Retrieves all active subscriptions for a specific user.
     * @param userId The ID of the user.
     * @returns An array of active subscriptions.
     */
    public async getActiveSubscriptionsByUserId(userId: string): Promise<Subscription[]> {
        logger.debug(`Fetching active subscriptions for User: ${userId}`);
        const allSubs = await this.subscriptionRepo.findByUserId(userId);
        
        return allSubs.filter(sub => 
            sub.status === SubscriptionStatus.ACTIVE || sub.status === SubscriptionStatus.TRIALING
        );
    }

    /**
     * AE4: Updates the status of an existing subscription.
     * @param subscriptionId The ID of the subscription to update.
     * @param newStatus The new status.
     * @returns The updated subscription object.
     * @throws Error if the subscription is not found.
     */
    public async updateSubscriptionStatus(subscriptionId: string, newStatus: SubscriptionStatus): Promise<Subscription> {
        logger.info(`Updating subscription ${subscriptionId} status to ${newStatus}`);
        const subscription = await this.getSubscriptionById(subscriptionId);

        if (!subscription) {
            throw new Error(`Subscription not found: ${subscriptionId}`);
        }

        subscription.status = newStatus;
        subscription.updatedAt = new Date();

        if (newStatus === SubscriptionStatus.CANCELED || newStatus === SubscriptionStatus.EXPIRED) {
            subscription.cancellationDate = new Date();
        }

        const updatedSub = await this.subscriptionRepo.save(subscription);
        logger.info(`Subscription ${subscriptionId} status updated to ${newStatus}`);
        return updatedSub;
    }

    /**
     * AE5: Links a Stripe Subscription ID to an internal subscription record.
     * @param subscriptionId The internal subscription ID.
     * @param stripeSubscriptionId The ID returned by Stripe.
     * @returns The updated subscription object.
     */
    public async linkStripeSubscription(subscriptionId: string, stripeSubscriptionId: string): Promise<Subscription> {
        logger.info(`Linking Stripe ID ${stripeSubscriptionId} to internal sub ${subscriptionId}`);
        const subscription = await this.getSubscriptionById(subscriptionId);

        if (!subscription) {
            throw new Error(`Subscription not found for linking: ${subscriptionId}`);
        }

        subscription.stripeSubscriptionId = stripeSubscriptionId;
        subscription.updatedAt = new Date();
        
        return this.subscriptionRepo.save(subscription);
    }

    /**
     * AE6: Handles the successful creation of a subscription via Stripe checkout.
     * This involves creating the local record and linking the Stripe ID.
     * @param userId The user initiating the purchase.
     * @param planId The plan being purchased.
     * @param stripeCustomerId The customer ID from Stripe.
     * @param stripeSubscriptionId The subscription ID from Stripe.
     * @returns The newly created and linked Subscription object.
     */
    public async handleSuccessfulStripeSubscriptionCreation(
        userId: string, 
        planId: string, 
        stripeCustomerId: string, 
        stripeSubscriptionId: string
    ): Promise<Subscription> {
        logger.info(`Handling successful Stripe creation for User ${userId}, Plan ${planId}`);
        
        // 1. Create initial local record (AE1 logic embedded/adapted)
        let subscription: Subscription = {
            id: uuidv4(),
            userId: userId,
            planId: planId,
            status: SubscriptionStatus.TRIALING, // Will be updated to ACTIVE shortly after confirmation
            startDate: new Date(),
            endDate: new Date(Date.now() + 7 * 24 * 60 * 60 * 1000), // Placeholder, actual end date comes from Stripe webhook
            createdAt: new Date(),
            updatedAt: new Date(),
            stripeSubscriptionId: stripeSubscriptionId,
            cancellationDate: null,
        };

        // 2. Save to repository
        subscription = await this.subscriptionRepo.save(subscription);
        
        // Note: In a real system, we might also store stripeCustomerId on the User entity, 
        // but for this service scope, we focus on the Subscription entity.
        
        logger.info(`Subscription ${subscription.id} successfully created and linked to Stripe ${stripeSubscriptionId}`);
        return subscription;
    }

    /**
     * AE7: Initiates the process to cancel a subscription immediately (hard cancellation).
     * This calls Stripe to cancel immediately and updates the local status to CANCELED.
     * @param subscriptionId The internal subscription ID.
     * @returns The updated subscription object.
     */
    public async cancelSubscriptionImmediately(subscriptionId: string): Promise<Subscription> {
        const subscription = await this.getSubscriptionById(subscriptionId);

        if (!subscription || !subscription.stripeSubscriptionId) {
            throw new Error(`Subscription ${subscriptionId} not found or missing Stripe ID.`);
        }

        logger.warn(`Forcing immediate cancellation for Sub ${subscriptionId} via Stripe.`);
        
        // 1. Call Stripe to cancel immediately
        await this.stripeService.cancelSubscription(subscription.stripeSubscriptionId, true);

        // 2. Update local status (AE4 logic)
        return this.updateSubscriptionStatus(subscriptionId, SubscriptionStatus.CANCELED);
    }

    /**
     * AE8: Initiates the process to cancel a subscription at the end of the current billing cycle (soft cancellation).
     * This calls Stripe to schedule cancellation and updates the local status to SCHEDULED_FOR_CANCELLATION.
     * @param subscriptionId The internal subscription ID.
     * @returns The updated subscription object.
     */
    public async cancelSubscriptionAtPeriodEnd(subscriptionId: string): Promise<Subscription> {
        const subscription = await this.getSubscriptionById(subscriptionId);

        if (!subscription || !subscription.stripeSubscriptionId) {
            throw new Error(`Subscription ${subscriptionId} not found or missing Stripe ID.`);
        }

        logger.info(`Scheduling cancellation for Sub ${subscriptionId} at period end via Stripe.`);
        
        // 1. Call Stripe to schedule cancellation
        await this.stripeService.cancelSubscription(subscription.stripeSubscriptionId, false);

        // 2. Update local status (AE4 logic adaptation)
        return this.updateSubscriptionStatus(subscriptionId, SubscriptionStatus.SCHEDULED_FOR_CANCELLATION);
    }

    /**
     * AE9: Retrieves the current plan details associated with an active subscription.
     * Assumes the existence of a separate PlanService or direct access to plan data structure.
     * For this implementation, we mock fetching plan details based on planId.
     * @param subscriptionId The internal subscription ID.
     * @returns The SubscriptionPlan object.
     */
    public async getCurrentPlanDetails(subscriptionId: string): Promise<SubscriptionPlan> {
        const subscription = await this.getSubscriptionById(subscriptionId);

        if (!subscription) {
            throw new Error(`Subscription ${subscriptionId} not found.`);
        }

        // Mocking Plan retrieval based on planId
        logger.debug(`Retrieving plan details for Plan ID: ${subscription.planId}`);
        
        // In a real application, this would call a PlanService or look up in a PlanRepository
        const mockPlan: SubscriptionPlan = {
            id: subscription.planId,
            name: `Plan ${subscription.planId.substring(0, 4)}`,
            price: 9.99,
            interval: 'month',
            features: ['Feature A', 'Feature B']
        };

        return mockPlan;
    }

    /**
     * AE26: Retrieves all subscriptions associated with a specific Stripe Customer ID.
     * @param stripeCustomerId The ID from Stripe.
     * @returns An array of subscriptions.
     */
    public async getSubscriptionsByStripeCustomerId(stripeCustomerId: string): Promise<Subscription[]> {
        logger.debug(`Fetching subscriptions for Stripe Customer ID: ${stripeCustomerId}`);
        return this.subscriptionRepo.findByStripeCustomerId(stripeCustomerId);
    }

    /**
     * AE27: Checks if a user has any active subscription.
     * @param userId The ID of the user.
     * @returns True if at least one active subscription exists, false otherwise.
     */
    public async hasActiveSubscription(userId: string): Promise<boolean> {
        const activeSubs = await this.getActiveSubscriptionsByUserId(userId);
        return activeSubs.length > 0;
    }

    /**
     * AE28: Checks if a user has a specific subscription active.
     * @param userId The ID of the user.
     * @param planId The ID of the plan to check for.
     * @returns True if an active subscription for that plan exists, false otherwise.
     */
    public async hasActiveSubscriptionForPlan(userId: string, planId: string): Promise<boolean> {
        const activeSubs = await this.getActiveSubscriptionsByUserId(userId);
        return activeSubs.some(sub => sub.planId === planId);
    }

    /**
     * AE35: Handles the webhook event for subscription creation/activation from Stripe.
     * Updates the local record to ACTIVE and sets accurate dates based on Stripe data.
     * @param stripeSubscriptionId The ID from Stripe.
     * @param startDate Unix timestamp of subscription start.
     * @param endDate Unix timestamp of subscription end/current period end.
     * @param stripeCustomerId The customer ID associated.
     * @returns The updated Subscription object.
     */
    public async handleStripeSubscriptionActivated(
        stripeSubscriptionId: string, 
        startDate: number, 
        endDate: number,
        stripeCustomerId: string
    ): Promise<Subscription> {
        logger.info(`Webhook: Activating subscription for Stripe ID ${stripeSubscriptionId}`);
        
        let subscription = await this.subscriptionRepo.findByStripeSubscriptionId(stripeSubscriptionId);

        if (!subscription) {
            // This scenario might happen if the local record creation (AE6) failed or was missed.
            // We attempt to create a placeholder record if we can infer the user/plan, 
            // but for safety, we usually require the user context or fail loudly.
            logger.error(`Could not find local subscription for Stripe ID ${stripeSubscriptionId}. Cannot update dates.`);
            throw new Error(`Local subscription record not found for Stripe ID: ${stripeSubscriptionId}`);
        }

        // AE37: Update dates and status
        subscription.status = SubscriptionStatus.ACTIVE;
        subscription.startDate = new Date(startDate * 1000);
        subscription.endDate = new Date(endDate * 1000);
        subscription.updatedAt = new Date();
        
        // Ensure Stripe Customer ID is synced if we stored it locally (AE26 context)
        // Assuming we might need to update the user context if we had access to UserRepo here, 
        // but for this service, we ensure the subscription record is correct.
        
        return this.subscriptionRepo.save(subscription);
    }

    /**
     * AE36: Handles the webhook event for subscription renewal/update from Stripe.
     * Updates the local record's end date and ensures status remains ACTIVE.
     * @param stripeSubscriptionId The ID from Stripe.
     * @param newEndDate Unix timestamp of the new billing period end.
     * @returns The updated Subscription object.
     */
    public async handleStripeSubscriptionUpdated(
        stripeSubscriptionId: string, 
        newEndDate: number
    ): Promise<Subscription> {
        logger.info(`Webhook: Updating billing cycle for Stripe ID ${stripeSubscriptionId}`);
        
        let subscription = await this.subscriptionRepo.findByStripeSubscriptionId(stripeSubscriptionId);

        if (!subscription) {
            throw new Error(`Local subscription record not found for Stripe ID: ${stripeSubscriptionId}`);
        }

        if (subscription.status === SubscriptionStatus.ACTIVE || subscription.status === SubscriptionStatus.TRIALING) {
            subscription.endDate = new Date(newEndDate * 1000);
            subscription.updatedAt = new Date();
            return this.subscriptionRepo.save(subscription);
        } else {
            logger.warn(`Received update for non-active subscription ${subscription.id} (${subscription.status}). Ignoring date update.`);
            return subscription;
        }
    }

    /**
     * AE37: Handles the webhook event for subscription cancellation from Stripe.
     * Updates the local record status to SCHEDULED_FOR_CANCELLATION and sets the cancellation date
     * to the period end date provided by Stripe.
     * @param stripeSubscriptionId The ID from Stripe.
     * @param periodEnd Unix timestamp when the subscription officially ends.
     * @returns The updated Subscription object.
     */
    public async handleStripeSubscriptionCancelled(
        stripeSubscriptionId: string, 
        periodEnd: number
    ): Promise<Subscription> {
        logger.warn(`Webhook: Subscription ${stripeSubscriptionId} marked for cancellation.`);
        
        let subscription = await this.subscriptionRepo.findByStripeSubscriptionId(stripeSubscriptionId);

        if (!subscription) {
            throw new Error(`Local subscription record not found for Stripe ID: ${stripeSubscriptionId}`);
        }

        // AE4 logic applied here for cancellation scheduling
        subscription.status = SubscriptionStatus.SCHEDULED_FOR_CANCELLATION;
        subscription.cancellationDate = new Date(periodEnd * 1000);
        subscription.updatedAt = new Date();
        
        return this.subscriptionRepo.save(subscription);
    }

    /**
     * AE39: Handles the webhook event for subscription deletion/final expiration (e.g., failed payment leading to deletion).
     * Updates the local record status to EXPIRED.
     * @param stripeSubscriptionId The ID from Stripe.
     * @returns The updated Subscription object.
     */
    public async handleStripeSubscriptionDeleted(stripeSubscriptionId: string): Promise<Subscription> {
        logger.error(`Webhook: Subscription ${stripeSubscriptionId} deleted/expired permanently.`);
        
        let subscription = await this.subscriptionRepo.findByStripeSubscriptionId(stripeSubscriptionId);

        if (!subscription) {
            throw new Error(`Local subscription record not found for Stripe ID: ${stripeSubscriptionId}`);
        }

        // AE4 logic applied here for final expiration
        return this.updateSubscriptionStatus(subscription.id, SubscriptionStatus.EXPIRED);
    }

    /**
     * AE40: Handles the webhook event for payment failure leading to an overdue state.
     * Updates the local record status to PAST_DUE.
     * @param stripeSubscriptionId The ID from Stripe.
     * @returns The updated Subscription object.
     */
    public async handleStripePaymentFailed(stripeSubscriptionId: string): Promise<Subscription> {
        logger.error(`Webhook: Payment failed for Stripe ID ${stripeSubscriptionId}. Setting status to PAST_DUE.`);
        
        let subscription = await this.subscriptionRepo.findByStripeSubscriptionId(stripeSubscriptionId);

        if (!subscription) {
            throw new Error(`Local subscription record not found for Stripe ID: ${stripeSubscriptionId}`);
        }

        if (subscription.status === SubscriptionStatus.ACTIVE) {
            return this.updateSubscriptionStatus(subscription.id, SubscriptionStatus.PAST_DUE);
        }
        
        logger.warn(`Payment failed for subscription ${subscription.id} which was already in status ${subscription.status}. Status remains unchanged.`);
        return subscription;
    }

    /**
     * AE45: Retrieves the subscription history for a user, including canceled and expired ones.
     * @param userId The ID of the user.
     * @returns An array of all historical and current subscriptions.
     */
    public async getSubscriptionHistory(userId: string): Promise<Subscription[]> {
        logger.debug(`Retrieving full subscription history for User: ${userId}`);
        return this.subscriptionRepo.findByUserId(userId);
    }

    /**
     * AE46: Checks if a subscription is currently in a grace period (e.g., PAST_DUE).
     * @param subscriptionId The ID of the subscription.
     * @returns True if the subscription status indicates a grace period.
     */
    public isSubscriptionInGracePeriod(subscription: Subscription): boolean {
        const graceStatuses = [SubscriptionStatus.PAST_DUE, SubscriptionStatus.TRIALING];
        return graceStatuses.includes(subscription.status);
    }

    /**
     * AE47: Checks if a subscription is currently active or in a grace period.
     * @param subscriptionId The ID of the subscription.
     * @returns True if the subscription is usable.
     */
    public isSubscriptionActiveOrGraceful(subscription: Subscription): boolean {
        const usableStatuses = [
            SubscriptionStatus.ACTIVE, 
            SubscriptionStatus.TRIALING, 
            SubscriptionStatus.PAST_DUE
        ];
        return usableStatuses.includes(subscription.status);
    }

    /**
     * AE48: Retrieves the Stripe Subscription ID for a given internal subscription ID.
     * @param subscriptionId The internal ID.
     * @returns The Stripe Subscription ID or null.
     */
    public async getStripeSubscriptionId(subscriptionId: string): Promise<string | null> {
        const subscription = await this.getSubscriptionById(subscriptionId);
        return subscription ? subscription.stripeSubscriptionId : null;
    }

    /**
     * AE54: Allows upgrading a subscription plan via Stripe.
     * This involves fetching the current Stripe ID, calling Stripe to update the subscription,
     * and then updating the local planId and potentially the end date.
     * @param subscriptionId The internal subscription ID to upgrade.
     * @param newPlanId The ID of the new plan.
     * @returns The updated Subscription object.
     */
    public async upgradeSubscription(subscriptionId: string, newPlanId: string): Promise<Subscription> {
        const subscription = await this.getSubscriptionById(subscriptionId);

        if (!subscription || !subscription.stripeSubscriptionId) {
            throw new Error(`Cannot upgrade: Subscription ${subscriptionId} not found or lacks Stripe ID.`);
        }

        logger.info(`Upgrading subscription ${subscriptionId} from ${subscription.planId} to ${newPlanId}`);

        // 1. Call Stripe to handle the upgrade logic (proration, etc.)
        const stripeUpdateResult = await this.stripeService.updateSubscriptionPlan(
            subscription.stripeSubscriptionId, 
            newPlanId
        );

        // 2. Update local record
        subscription.planId = newPlanId;
        subscription.updatedAt = new Date();
        
        // Update end date based on Stripe's response if available (AE36 logic applied)
        if (stripeUpdateResult.current_period_end) {
            subscription.endDate = new Date(stripeUpdateResult.current_period_end * 1000);
        }

        return this.subscriptionRepo.save(subscription);
    }

    /**
     * AE55: Allows downgrading a subscription plan via Stripe.
     * This typically schedules the downgrade for the end of the current period unless immediate downgrade is forced.
     * @param subscriptionId The internal subscription ID to downgrade.
     * @param newPlanId The ID of the new plan.
     * @returns The updated Subscription object.
     */
    public async downgradeSubscription(subscriptionId: string, newPlanId: string): Promise<Subscription> {
        const subscription = await this.getSubscriptionById(subscriptionId);

        if (!subscription || !subscription.stripeSubscriptionId) {
            throw new Error(`Cannot downgrade: Subscription ${subscriptionId} not found or lacks Stripe ID.`);
        }

        logger.info(`Downgrading subscription ${subscriptionId} from ${subscription.planId} to ${newPlanId} (scheduled for period end).`);

        // Stripe handles downgrades usually by setting the new item to take effect at period end.
        const stripeUpdateResult = await this.stripeService.updateSubscriptionPlan(
            subscription.stripeSubscriptionId, 
            newPlanId,
            true // Schedule for end of period
        );

        // 2. Update local record
        subscription.planId = newPlanId;
        subscription.status = SubscriptionStatus.SCHEDULED_FOR_CANCELLATION; // Downgrade often implies scheduling the change
        subscription.updatedAt = new Date();
        
        if (stripeUpdateResult.current_period_end) {
            subscription.endDate = new Date(stripeUpdateResult.current_period_end * 1000);
        }

        return this.subscriptionRepo.save(subscription);
    }

    /**
     * AE56: Retrieves the current status of a subscription record.
     * @param subscriptionId The ID of the subscription.
     * @returns The SubscriptionStatus enum value.
     */
    public async getSubscriptionStatus(subscriptionId: string): Promise<SubscriptionStatus> {
        const subscription = await this.getSubscriptionById(subscriptionId);
        if (!subscription) {
            throw new Error(`Subscription ${subscriptionId} not found.`);
        }
        return subscription.status;
    }
}
