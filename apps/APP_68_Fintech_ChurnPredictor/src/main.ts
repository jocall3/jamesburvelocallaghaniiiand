// --- API ROUTES ---
server.post('/v1/predict', {
    schema: {
        body: ChurnPredictionRequestSchema,
        response: {
            202: {
                type: 'object',
                properties: {
                    jobId: { type: 'string' },
                    statusUrl: { type: 'string' },
                },
            },
        },
    },
}, async (request: FastifyRequest<{ Body: ChurnPredictionRequest }>, reply: FastifyReply) => {
    const jobId = await predictionService.startPredictionJob(request.body);
    reply.code(202).send({
        jobId,
        statusUrl: `/v1/predictions/${jobId}`,
    });
});

server.get('/v1/predictions/:jobId', async (request: FastifyRequest<{ Params: { jobId: string } }>, reply: FastifyReply) => {
    const { jobId } = request.params;
    const result = jobStore.get(jobId);

    if (!result) {
        return reply.code(404).send({ error: 'Job not found' });
    }

    return reply.send(result);
});

