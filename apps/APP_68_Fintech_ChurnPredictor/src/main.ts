// --- CORE BUSINESS LOGIC SERVICES ---
class FeatureEngineeringService {
    async createFeatures(request: ChurnPredictionRequest, sentimentProvider: SentimentAnalysisProvider): Promise<{ features: Record<string, number>, sentimentMeta: any }> {
        const { interactions, jurisdiction } = request;
        const now = new Date();

        // Basic features
        const logins = interactions.filter(i => i.type === 'login');
        const lastLogin = logins.length > 0 ? new Date(logins.sort((a, b) => new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime())[0].timestamp) : now;
        const daysSinceLastLogin = (now.getTime() - lastLogin.getTime()) / (1000 * 3600 * 24);

        const transactions = interactions.filter(i => i.type === 'transaction');
        const transactionFrequency = transactions.length / 30; // transactions per month (assuming 30 day window)

        // Sentiment features
        let sentimentMeta = null;
        let avgSentiment = 0;

        // Jurisdictional feature flag check
        const flags = config.get('jurisdictionFeatureFlags')[jurisdiction] || {};
        if (flags.disable_text_analysis) {
            logger.warn(`Text analysis disabled for jurisdiction: ${jurisdiction}`);
            sentimentMeta = { provider: 'none', averageScore: 0, analyzedTickets: 0, tokens: 0, reason: 'Disabled by jurisdiction flag' };
        } else {
            const supportTickets = interactions.filter(i => i.type === 'support_ticket').map(i => i.metadata.text as string).filter(Boolean);
            if (supportTickets.length > 0) {
                const { scores, tokens } = await sentimentProvider.analyze(supportTickets);
                avgSentiment = scores.reduce((a, b) => a + b, 0) / scores.length;
                sentimentMeta = { provider: sentimentProvider.id, averageScore: avgSentiment, analyzedTickets: supportTickets.length, tokens };
            } else {
                sentimentMeta = { provider: sentimentProvider.id, averageScore: 0, analyzedTickets: 0, tokens: 0 };
            }
        }

        const features = {
            daysSinceLastLogin,
            transactionFrequency,
            supportTicketCount: interactions.filter(i => i.type === 'support_ticket').length,
            avgSentiment,
        };

        logger.info({ customerId: request.customerId, features }, 'Generated features for churn prediction.');
        return { features, sentimentMeta };
    }
}

class PredictionService {
    private featureService = new FeatureEngineeringService();

    async startPredictionJob(request: ChurnPredictionRequest): Promise<string> {
        const jobId = randomUUID();
        const job: ChurnPredictionResult = {
            jobId,
            customerId: request.customerId,
            status: 'PENDING',
            churnProbability: null,
            riskLevel: null,
            contributingFactors: [],
            modelUsed: '',
            sentimentAnalysis: null,
            cost: { sentimentTokens: 0, predictionUnits: 0, totalMicroCents: 0 },
            createdAt: new Date().toISOString(),
        };
        jobStore.set(jobId, job);

        // Asynchronously process the job
        this.processJob(jobId, request).catch(err => {
            logger.error({ jobId, err }, 'Unhandled error during async job processing.');
        });

        const event = new CloudEvent({
            source: agent_metadata.agent_id,
            type: Ontology.ChurnPrediction.Requested,
            subject: request.customerId,
            data: { jobId, customerId: request.customerId },
        });
        await eventBus.publish(event);

        return jobId;
    }

    private async processJob(jobId: string, request: ChurnPredictionRequest) {
        try {
            this.updateJobStatus(jobId, { status: 'PROCESSING' });

            const sentimentProviderId = request.modelConfig?.sentimentProviderId || config.get('defaultSentimentProvider');
            const predictionModelId = request.modelConfig?.predictionModelId || config.get('defaultPredictionModel');

            const sentimentProvider = providerRegistry.getSentimentProvider(sentimentProviderId);
            const predictionModel = providerRegistry.getPredictionModel(predictionModelId);

            const { features, sentimentMeta } = await this.featureService.createFeatures(request, sentimentProvider);
            const { probability, factors, units } = await predictionModel.predict(features);

            const riskLevel = probability > 0.7 ? 'HIGH' : probability > 0.4 ? 'MEDIUM' : 'LOW';

            // Unit economics calculation (example pricing)
            const sentimentCost = sentimentMeta.tokens * 0.5; // $0.50 per 1k tokens
            const predictionCost = units * 1000; // $1 per prediction unit
            const totalMicroCents = Math.round((sentimentCost + predictionCost) * 100);

            const finalResult: Partial<ChurnPredictionResult> = {
                status: 'COMPLETED',
                churnProbability: probability,
                riskLevel,
                contributingFactors: factors,
                modelUsed: predictionModel.id,
                sentimentAnalysis: sentimentMeta,
                cost: {
                    sentimentTokens: sentimentMeta.tokens,
                    predictionUnits: units,
                    totalMicroCents,
                },
                completedAt: new Date().toISOString(),
            };
            this.updateJobStatus(jobId, finalResult);

            const event = new CloudEvent({
                source: agent_metadata.agent_id,
                type: Ontology.ChurnPrediction.Completed,
                subject: request.customerId,
                data: jobStore.get(jobId),
            });
            await eventBus.publish(event);
            
            await audit.log({
                actor: { type: 'system', id: agent_metadata.agent_id },
                action: 'churn.predict',
                resource: { type: 'customer', id: request.customerId },
                outcome: 'success',
                details: { jobId, probability, riskLevel, model: predictionModel.id }
            });

        } catch (error: any) {
            logger.error({ jobId, error: error.message }, 'Churn prediction job failed.');
            this.updateJobStatus(jobId, {
                status: 'FAILED',
                error: error.message,
                completedAt: new Date().toISOString(),
            });
            const event = new CloudEvent({
                source: agent_metadata.agent_id,
                type: Ontology.ChurnPrediction.Failed,
                subject: request.customerId,
                data: { jobId, error: error.message },
            });
            await eventBus.publish(event);
        }
    }

    private updateJobStatus(jobId: string, updates: Partial<ChurnPredictionResult>) {
        const job = jobStore.get(jobId);
        if (job) {
            jobStore.set(jobId, { ...job, ...updates });
        }
    }
}

