function errorHandler(logger: Logger) {
    return (err: Error, req: Request, res: Response, next: NextFunction) => {
        logger.error(`[${(req as any).id}] Unhandled error: ${err.message}`, { stack: err.stack });

        if (err instanceof z.ZodError) {
            return res.status(400).json({ error: 'Invalid request payload', details: err.errors });
        }
        if (err instanceof BaseError) {
            return res.status(err.statusCode).json({ error: err.message, code: err.errorCode });
        }

        res.status(500).json({ error: 'Internal Server Error' });
    };
}

function auditLogger(deps: { eventBus: EventBusClient }) {
    return (req: AuthRequest, res: Response, next: NextFunction) => {
        const start = Date.now();
        res.on('finish', () => {
            const event: EcosystemEvent = {
                id: `evt-${uuidv4()}`,
                source: 'APP_31_Data_SyntheticDataForge',
                type: 'api.request.audited',
                timestamp: new Date().toISOString(),
                specversion: '1.0',
                data: {
                    requestId: (req as any).id,
                    method: req.method,
                    path: req.originalUrl,
                    statusCode: res.statusCode,
                    durationMs: Date.now() - start,
                    principal: req.auth,
                    ip: req.ip,
                },
            };
            deps.eventBus.publish(event.type, event.data).catch(err => console.error('Failed to publish audit event', err));
        });
        next();
    };
}

