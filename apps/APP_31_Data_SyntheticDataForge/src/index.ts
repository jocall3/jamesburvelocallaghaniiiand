/**
 * The main service orchestrating the entire synthetic data generation process.
 * This class embodies the core tension of the application: Cost vs. Quality.
 */
class SyntheticDataService {
    private logger: Logger;
    private config: AppConfig;
    private jobRepository: JobRepository;
    private qualityControlService: QualityControlService;
    private domainAdaptationService: DomainAdaptationService;
    private eventBus: EventBusClient;
    private providers: Map<string, IGenerationProvider> = new Map();
    // private costRouterApp: ServiceDiscovery.Service;
    // private usageTrackerApp: ServiceDiscovery.Service;

    constructor(deps: {
        logger: Logger;
        config: AppConfig;
        jobRepository: JobRepository;
        qualityControlService: QualityControlService;
        domainAdaptationService: DomainAdaptationService;
        eventBus: EventBusClient;
        // costRouterApp: ServiceDiscovery.Service;
        // usageTrackerApp: ServiceDiscovery.Service;
    }) {
        this.logger = deps.logger;
        this.config = deps.config;
        this.jobRepository = deps.jobRepository;
        this.qualityControlService = deps.qualityControlService;
        this.domainAdaptationService = deps.domainAdaptationService;
        this.eventBus = deps.eventBus;
        // this.costRouterApp = deps.costRouterApp;
        // this.usageTrackerApp = deps.usageTrackerApp;

        this.registerProviders();
    }

    private registerProviders() {
        // In a real system, this would be dynamic based on configuration
        const stabilityAdapter = new StabilityAiAdapter({ apiKey: this.config.providers.stability.apiKey }, this.logger);
        this.providers.set(stabilityAdapter.name, stabilityAdapter);

        const midjourneyAdapter = new MidjourneyAdapter({}, this.logger);
        this.providers.set(midjourneyAdapter.name, midjourneyAdapter);

        const openaiAdapter = new OpenAiTextAdapter({ apiKey: this.config.providers.openai.apiKey }, this.logger);
        this.providers.set(openaiAdapter.name, openaiAdapter);

        this.logger.info(`Registered providers: ${Array.from(this.providers.keys()).join(', ')}`);
    }

    async createJob(payload: CreateJobPayload, ownerId: string): Promise<SyntheticDataJob> {
        const job: SyntheticDataJob = {
            id: `job-${uuidv4()}`,
            name: payload.name,
            ownerId,
            status: 'pending',
            createdAt: new Date(),
            updatedAt: new Date(),
            config: payload,
            progress: {
                total: payload.quantity,
                completed: 0,
                failed: 0,
                quality_rejected: 0,
            },
        };

        const createdJob = await this.jobRepository.create(job);
        
        // Asynchronously start processing the job to avoid blocking the API response
        this.processJob(createdJob.id).catch(err => {
            this.logger.error(`Unhandled error in job processing for ${createdJob.id}:`, err);
        });

        await this.eventBus.publish('synthetic_data.job.created', {
            jobId: createdJob.id,
            ownerId,
            timestamp: new Date().toISOString(),
        });

        return createdJob;
    }

    /**
     * This is the core orchestration logic. It runs asynchronously.
     */
    private async processJob(jobId: string): Promise<void> {
        const job = await this.jobRepository.findById(jobId);
        if (!job || job.status !== 'pending') {
            this.logger.warn(`Job ${jobId} not found or not in pending state.`);
            return;
        }

        await this.jobRepository.update(jobId, { status: 'running' });
        this.logger.info(`Started processing job ${jobId}`);

        const { quantity, generationConfig, qualityControl, domainAdaptation } = job.config;
        const generatedItems: GeneratedDataItem[] = [];

        try {
            for (let i = 0; i < quantity; i++) {
                const promptInput = generationConfig.promptInputs[i % generationConfig.promptInputs.length];
                let sourcePrompt = this.hydratePrompt(generationConfig.promptTemplate, promptInput);

                if (domainAdaptation) {
                    sourcePrompt = await this.domainAdaptationService.adaptPrompt(sourcePrompt, domainAdaptation);
                }

                let item: GeneratedDataItem | null = null;
                let attempts = 0;
                const maxAttempts = qualityControl.enabled ? qualityControl.maxRegenerationAttempts + 1 : 1;

                while (!item && attempts < maxAttempts) {
                    attempts++;
                    const generationRequest: GenerationRequest = {
                        prompt: sourcePrompt,
                        dataType: job.config.dataType,
                        schema: job.config.schema,
                        jobId,
                        policy: generationConfig.policy,
                    };

                    const provider = await this.selectProvider(generationRequest);
                    const response = await provider.generate(generationRequest);

                    // Metering call to billing service
                    // await this.usageTrackerApp.post('/track', { ... });

                    let qcPassed = true;
                    let qcScore: number | undefined = undefined;

                    if (qualityControl.enabled) {
                        const tempItem: GeneratedDataItem = {
                            id: `item-${uuidv4()}`,
                            jobId,
                            sourcePrompt,
                            provider: response.provider,
                            model: response.model,
                            data: response.data,
                            metadata: response.metadata,
                            passedQc: false, // Will be updated
                        };
                        const qcResult = await this.qualityControlService.evaluate(tempItem, qualityControl.metrics);
                        qcPassed = qcResult.passed;
                        qcScore = qcResult.score;
                    }

                    if (qcPassed) {
                        item = {
                            id: `item-${uuidv4()}`,
                            jobId,
                            sourcePrompt,
                            provider: response.provider,
                            model: response.model,
                            data: response.data,
                            metadata: { ...response.metadata, cost: response.cost, latencyMs: response.latencyMs },
                            qualityScore: qcScore,
                            passedQc: true,
                        };
                        generatedItems.push(item);
                        job.progress.completed++;
                    } else {
                        job.progress.quality_rejected++;
                        this.logger.warn(`Item for job ${jobId} failed QC. Attempt ${attempts}/${maxAttempts}. Action: ${qualityControl.rejectionAction}`);
                        if (qualityControl.rejectionAction !== 'regenerate') {
                            break; // Stop trying for this item
                        }
                    }
                }

                if (!item) {
                    job.progress.failed++;
                }

                // Update progress periodically
                if (i % 10 === 0) {
                    await this.jobRepository.update(jobId, { progress: job.progress });
                }
            }

            // Finalize job
            const finalStatus: JobStatus = job.progress.failed > 0 ? 'partially_completed' : 'completed';
            await this.jobRepository.update(jobId, { status: finalStatus, progress: job.progress, resultsLocation: `s3://synthetic-data-forge/${jobId}` });
            this.logger.info(`Finished processing job ${jobId} with status: ${finalStatus}`);
            await this.eventBus.publish('synthetic_data.job.completed', { jobId, status: finalStatus });

        } catch (error: any) {
            this.logger.error(`Job ${jobId} failed with error:`, error);
            await this.jobRepository.update(jobId, { status: 'failed', error: error.message });
            await this.eventBus.publish('synthetic_data.job.failed', { jobId, error: error.message });
        }
    }

    /**
     * Selects a provider based on the job's policy. This is where the
     * Cost vs. Quality vs. Latency tension is resolved.
     */
    private async selectProvider(request: GenerationRequest): Promise<IGenerationProvider> {
        const { policy, dataType } = request;
        const availableProviders = Array.from(this.providers.values()).filter(p => p.supports(dataType));

        // In a real system, this would be a call to APP_01_Inference_CostRouter
        // which maintains real-time data on provider cost, latency, and quality scores.
        // For now, we use a simplified logic.
        
        switch (policy.mode) {
            case 'cost_optimized':
                // Mock logic: Stability is cheaper than Midjourney
                return this.providers.get('stability-ai')!;
            case 'quality_optimized':
                // Mock logic: Midjourney is higher quality
                return this.providers.get('midjourney')!;
            case 'latency_optimized':
                 // Mock logic: Stability is faster
                return this.providers.get('stability-ai')!;
            case 'balanced':
            default:
                // Simple balanced approach: alternate or random
                return Math.random() > 0.5 ? this.providers.get('stability-ai')! : this.providers.get('midjourney')!;
        }
    }

    private hydratePrompt(template: string, inputs: Record<string, any>): string {
        return template.replace(/\{(\w+)\}/g, (_, key) => inputs[key] || `{${key}}`);
    }
}

