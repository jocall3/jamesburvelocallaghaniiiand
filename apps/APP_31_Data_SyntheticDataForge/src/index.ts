/**
 * Manages the persistence of synthetic data generation jobs.
 * In a production environment, this would be backed by a robust database like
 * PostgreSQL or a NoSQL equivalent like DynamoDB. For this example, we use an
 * in-memory store to demonstrate the interface.
 */
class JobRepository {
    private jobs: Map<string, SyntheticDataJob> = new Map();
    private logger: Logger;

    constructor(dbConfig: any, logger: Logger) {
        this.logger = logger;
        this.logger.info(`Initializing JobRepository with config: ${JSON.stringify(dbConfig.type)}`);
        if (dbConfig.type !== 'in-memory') {
            this.logger.warn('In-memory repository is not suitable for production. Please configure a persistent database.');
        }
    }

    async create(job: SyntheticDataJob): Promise<SyntheticDataJob> {
        if (this.jobs.has(job.id)) {
            throw new BaseError(ErrorCodes.CONFLICT, `Job with ID ${job.id} already exists.`);
        }
        this.jobs.set(job.id, job);
        this.logger.info(`Created job ${job.id}`);
        return job;
    }

    async findById(id: string): Promise<SyntheticDataJob | null> {
        const job = this.jobs.get(id);
        return job ? { ...job } : null; // Return a copy
    }

    async findByOwner(ownerId: string): Promise<SyntheticDataJob[]> {
        return Array.from(this.jobs.values()).filter(job => job.ownerId === ownerId);
    }

    async update(id: string, updates: Partial<SyntheticDataJob>): Promise<SyntheticDataJob | null> {
        const job = this.jobs.get(id);
        if (!job) {
            return null;
        }
        const updatedJob = { ...job, ...updates, updatedAt: new Date() };
        this.jobs.set(id, updatedJob);
        this.logger.debug(`Updated job ${id}`);
        return updatedJob;
    }
}

