const app = express();
const PORT = process.env.PORT || 3009;
const SERVICE_NAME = 'APP_09_Agents_SwarmController';

// Middleware
app.use(helmet());
app.use(cors());
app.use(compression());
app.use(express.json({ limit: '1mb' }));

// Request Logging & Correlation
app.use((req: Request, res: Response, next: NextFunction) => {
    const traceId = req.headers['x-trace-id'] || uuidv4();
    (req as any).traceId = traceId;
    Logger.info(`[${req.method}] ${req.path}`, { traceId, ip: req.ip });
    next();
});

// Initialize Engine
const swarmEngine = new SwarmEngine();

// ------------------------------------------------------------------------
// API ROUTES
// ------------------------------------------------------------------------

// Health Check
app.get('/health', (req, res) => {
    res.json({ status: 'OK', timestamp: new Date().toISOString(), service: SERVICE_NAME });
});

// 1. Register Agent
app.post('/v1/agents/register', (req, res) => {
    try {
        const config: AgentConfig = {
            id: req.body.id || `agent_${uuidv4()}`,
            ...req.body
        };
        swarmEngine.registerAgent(config);
        res.status(201).json({ success: true, agentId: config.id });
    } catch (e: any) {
        res.status(400).json({ error: e.message });
    }
});

// 2. Create Swarm
app.post('/v1/swarm/create', (req, res) => {
    try {
        const { name, agentIds, strategy } = req.body;
        if (!name || !agentIds || !strategy) throw new Error("Missing required fields");
        
        const swarm = swarmEngine.createSwarm(name, agentIds, strategy);
        res.status(201).json(swarm);
    } catch (e: any) {
        res.status(400).json({ error: e.message });
    }
});

// 3. Dispatch Task
app.post('/v1/swarm/:id/dispatch', async (req, res) => {
    try {
        const { input } = req.body;
        const swarmId = req.params.id;
        const traceId = (req as any).traceId;

        const task = await swarmEngine.dispatchTask(swarmId, input, traceId);
        res.status(202).json({ taskId: task.id, status: task.status, trackingUrl: `/v1/tasks/${task.id}` });
    } catch (e: any) {
        res.status(404).json({ error: e.message });
    }
});

// 4. Get Task Status
app.get('/v1/tasks/:id', (req, res) => {
    const task = swarmEngine.getTask(req.params.id);
    if (!task) return res.status(404).json({ error: "Task not found" });
    res.json(task);
});

// 5. Get Swarm Status
app.get('/v1/swarm/:id', (req, res) => {
    const swarm = swarmEngine.getSwarm(req.params.id);
    if (!swarm) return res.status(404).json({ error: "Swarm not found" });
    res.json(swarm);
});

