export function createExplainer(
    logger: Logger, 
    eventBus: EventBus, 
    primary: AIProvider, 
    verifier: AIProvider
) {
    return new ExplainerService(logger, eventBus, primary, verifier, {
        skipVerification: process.env.SKIP_VERIFICATION === 'true',
        jurisdictionDefault: 'US_GENERIC'
    });
}