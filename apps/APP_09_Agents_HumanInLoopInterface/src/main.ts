class AIGateway {
    async analyzeRisk(payload: any): Promise<{ score: number; reasoning: string }> {
        // MOCK: Integration with OpenAI for risk scoring
        // In production: Call OpenAI API with a prompt designed to detect dangerous actions
        // (e.g., PII leakage, financial transactions, system deletion).
        
        const payloadStr = JSON.stringify(payload);
        const isHighRisk = payloadStr.includes('DELETE') || payloadStr.includes('transfer') || payloadStr.includes('sudo');
        
        // Simulating latency
        await new Promise(resolve => setTimeout(resolve, 150));

        if (isHighRisk) {
            return { score: 0.85, reasoning: 'Detected high-stakes keywords (DELETE/transfer).' };
        }
        return { score: 0.1, reasoning: 'Routine operation detected.' };
    }

    async summarizeContext(workflow: WorkflowContext): Promise<string> {
        // MOCK: Integration with Anthropic for context summarization
        // In production: Send workflow history to Claude for a human-readable summary.
        return `Workflow ${workflow.workflowId} initiated by ${workflow.initiatedBy.userId}. Step ${workflow.currentStepIndex + 1} involves action '${workflow.steps[workflow.currentStepIndex].actionType}'.`;
    }
}

/**
 * Manages the lifecycle of workflows and state transitions.
 */
class WorkflowEngine {
    private workflows: Map<string, WorkflowContext> = new Map();
    private eventBus: EventEmitter;
    private aiGateway: AIGateway;
    private reviewManager: ReviewManager;

    constructor(eventBus: EventEmitter, reviewManager: ReviewManager) {
        this.eventBus = eventBus;
        this.aiGateway = new AIGateway();
        this.reviewManager = reviewManager;
    }

    public async createWorkflow(agentId: string, identity: IdentityContext, steps: WorkflowStep[]): Promise<WorkflowContext> {
        const id = crypto.randomUUID();
        const workflow: WorkflowContext = {
            workflowId: id,
            agentId,
            initiatedBy: identity,
            steps,
            currentStepIndex: 0,
            status: WorkflowStatus.PENDING,
            metadata: {},
            createdAt: new Date(),
            updatedAt: new Date()
        };

        this.workflows.set(id, workflow);
        Logger.audit('WORKFLOW_CREATED', identity, { workflowId: id, stepCount: steps.length });
        
        // Start execution asynchronously
        this.executeStep(id);
        
        return workflow;
    }

    public getWorkflow(id: string): WorkflowContext | undefined {
        return this.workflows.get(id);
    }

    private async executeStep(workflowId: string) {
        const workflow = this.workflows.get(workflowId);
        if (!workflow) return;

        if (workflow.currentStepIndex >= workflow.steps.length) {
            workflow.status = WorkflowStatus.COMPLETED;
            workflow.updatedAt = new Date();
            Logger.log('info', `Workflow ${workflowId} completed successfully.`);
            return;
        }

        const currentStep = workflow.steps[workflow.currentStepIndex];
        workflow.status = WorkflowStatus.RUNNING;

        // 1. Evaluate Risk
        const riskAnalysis = await this.aiGateway.analyzeRisk(currentStep.payload);
        currentStep.riskScore = riskAnalysis.score;
        currentStep.riskLevel = this.mapScoreToLevel(riskAnalysis.score);

        Logger.log('info', `Step Analysis: ID=${currentStep.id} Risk=${currentStep.riskScore} Conf=${currentStep.aiConfidenceScore}`);

        // 2. Determine if Review is Needed
        const needsReview = this.shouldPauseForReview(currentStep);

        if (needsReview) {
            workflow.status = WorkflowStatus.PAUSED_FOR_REVIEW;
            workflow.updatedAt = new Date();
            
            const summary = await this.aiGateway.summarizeContext(workflow);
            
            await this.reviewManager.createReviewRequest({
                workflowId,
                stepId: currentStep.id,
                reason: `Risk Score (${currentStep.riskScore}) exceeded threshold or Confidence (${currentStep.aiConfidenceScore}) was too low.`,
                aiSummary: summary,
                riskAnalysis: riskAnalysis.reasoning,
                requiredRole: currentStep.riskLevel === RiskLevel.CRITICAL ? 'admin' : 'operator',
                payload: currentStep.payload
            });

            Logger.log('warn', `Workflow ${workflowId} paused for human review.`);
        } else {
            // Auto-approve and proceed
            currentStep.status = 'EXECUTED';
            workflow.currentStepIndex++;
            workflow.updatedAt = new Date();
            // Recursively execute next step
            setImmediate(() => this.executeStep(workflowId));
        }
    }

    public async resumeWorkflow(workflowId: string, approved: boolean, modification?: Record<string, any>) {
        const workflow = this.workflows.get(workflowId);
        if (!workflow) throw new Error('Workflow not found');

        if (workflow.status !== WorkflowStatus.PAUSED_FOR_REVIEW) {
            throw new Error('Workflow is not paused for review');
        }

        const currentStep = workflow.steps[workflow.currentStepIndex];

        if (approved) {
            if (modification) {
                Logger.log('info', `Applying human modification to step ${currentStep.id}`);
                currentStep.payload = modification;
            }
            workflow.status = WorkflowStatus.APPROVED; // Transient state
            currentStep.status = 'EXECUTED';
            workflow.currentStepIndex++;
            workflow.updatedAt = new Date();
            setImmediate(() => this.executeStep(workflowId));
        } else {
            workflow.status = WorkflowStatus.REJECTED;
            workflow.updatedAt = new Date();
            Logger.log('warn', `Workflow ${workflowId} rejected by human reviewer.`);
        }
    }

    private shouldPauseForReview(step: WorkflowStep): boolean {
        // Rule 1: Low Confidence
        if (step.aiConfidenceScore < CONFIG.autoApproveConfidence) return true;

        // Rule 2: High Risk
        if ((step.riskScore || 0) > CONFIG.riskThreshold) return true;

        // Rule 3: Explicit High Stakes Actions (Hardcoded Safety)
        const action = step.actionType.toUpperCase();
        const restrictedActions = ['DELETE_DB', 'TRANSFER_FUNDS', 'PUBLISH_KEY', 'GRANT_ADMIN'];
        if (restrictedActions.includes(action)) return true;

        return false;
    }

    private mapScoreToLevel(score: number): RiskLevel {
        if (score > 0.9) return RiskLevel.CRITICAL;
        if (score > 0.7) return RiskLevel.HIGH;
        if (score > 0.4) return RiskLevel.MEDIUM;
        return RiskLevel.LOW;
    }
}

/**
 * Manages the queue of pending human reviews.
 */
class ReviewManager {
    private reviews: Map<string, ReviewRequest> = new Map();
    private eventBus: EventEmitter;

    constructor(eventBus: EventEmitter) {
        this.eventBus = eventBus;
    }

    public async createReviewRequest(params: {
        workflowId: string;
        stepId: string;
        reason: string;
        aiSummary: string;
        riskAnalysis: string;
        requiredRole: string;
        payload: any;
    }): Promise<ReviewRequest> {
        const id = crypto.randomUUID();
        const request: ReviewRequest = {
            id,
            workflowId: params.workflowId,
            stepId: params.stepId,
            reason: params.reason,
            aiSummary: params.aiSummary,
            riskAnalysis: params.riskAnalysis,
            requiredRole: params.requiredRole,
            status: 'PENDING',
            createdAt: new Date(),
            expiresAt: new Date(Date.now() + 24 * 60 * 60 * 1000) // 24h expiry
        };

        this.reviews.set(id, request);
        
        // Emit event for external notification systems (e.g., Slack bot)
        this.eventBus.emit('review:created', request);
        
        return request;
    }

    public getPendingReviews(role?: string): ReviewRequest[] {
        return Array.from(this.reviews.values())
            .filter(r => r.status === 'PENDING')
            .filter(r => !role || r.requiredRole === role);
    }

    public getReview(id: string): ReviewRequest | undefined {
        return this.reviews.get(id);
    }

    public async submitDecision(
        reviewId: string, 
        reviewer: IdentityContext, 
        decision: 'APPROVE' | 'REJECT', 
        comments?: string,
        modification?: Record<string, any>
    ): Promise<ReviewRequest> {
        const review = this.reviews.get(reviewId);
        if (!review) throw new Error('Review not found');
        if (review.status !== 'PENDING') throw new Error('Review already processed');

        // Check permissions
        if (!reviewer.roles.includes('admin') && !reviewer.roles.includes(review.requiredRole)) {
            throw new Error('Insufficient permissions to review this item');
        }

        review.status = decision === 'APPROVE' ? 'APPROVED' : 'REJECTED';
        review.reviewerId = reviewer.userId;
        review.reviewerComments = comments;
        review.modificationPayload = modification;

        Logger.audit('REVIEW_DECISION', reviewer, {
            reviewId,
            decision,
            workflowId: review.workflowId
        });

        this.eventBus.emit('review:decided', { reviewId, decision, modification });
        return review;
    }
}

