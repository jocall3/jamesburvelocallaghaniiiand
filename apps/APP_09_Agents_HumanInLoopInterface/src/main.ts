import * as http from 'http';

class AppServer {
    private server: http.Server;
    private workflowEngine: WorkflowEngine;
    private reviewManager: ReviewManager;
    private eventBus: EventEmitter;

    constructor() {
        this.eventBus = new EventEmitter();
        this.reviewManager = new ReviewManager(this.eventBus);
        this.workflowEngine = new WorkflowEngine(this.eventBus, this.reviewManager);

        // Wire up event listeners
        this.eventBus.on('review:decided', async (event) => {
            const review = this.reviewManager.getReview(event.reviewId);
            if (review) {
                await this.workflowEngine.resumeWorkflow(
                    review.workflowId, 
                    event.decision === 'APPROVE', 
                    event.modification
                );
            }
        });

        this.server = http.createServer(this.handleRequest.bind(this));
    }

    public start() {
        this.server.listen(CONFIG.port, () => {
            Logger.log('info', `APP_09_HITL running on port ${CONFIG.port}`);
        });
    }

    private async handleRequest(req: http.IncomingMessage, res: http.ServerResponse) {
        // Basic CORS
        res.setHeader('Access-Control-Allow-Origin', '*');
        res.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
        res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');

        if (req.method === 'OPTIONS') {
            res.writeHead(204);
            res.end();
            return;
        }

        const url = new URL(req.url || '', `http://${req.headers.host}`);
        const path = url.pathname;

        try {
            // -----------------------------------------------------------------
            // ENDPOINTS
            // -----------------------------------------------------------------

            // 1. Submit Workflow
            if (path === '/workflows' && req.method === 'POST') {
                const body = await this.parseBody(req);
                // Mock Identity
                const identity: IdentityContext = {
                    userId: req.headers['x-user-id'] as string || 'anon',
                    orgId: 'org_default',
                    roles: ['operator'],
                    permissions: [],
                    auditTraceId: crypto.randomUUID()
                };
                
                const workflow = await this.workflowEngine.createWorkflow(
                    body.agentId, 
                    identity, 
                    body.steps
                );
                this.sendJson(res, 201, workflow);
                return;
            }

            // 2. Get Workflow Status
            if (path.match(/^\/workflows\/[\w-]+$/) && req.method === 'GET') {
                const id = path.split('/')[2];
                const workflow = this.workflowEngine.getWorkflow(id);
                if (!workflow) {
                    this.sendJson(res, 404, { error: 'Workflow not found' });
                    return;
                }
                this.sendJson(res, 200, workflow);
                return;
            }

            // 3. List Pending Reviews
            if (path === '/reviews' && req.method === 'GET') {
                const role = url.searchParams.get('role') || undefined;
                const reviews = this.reviewManager.getPendingReviews(role);
                this.sendJson(res, 200, { count: reviews.length, reviews });
                return;
            }

            // 4. Submit Review Decision
            if (path.match(/^\/reviews\/[\w-]+\/decision$/) && req.method === 'POST') {
                const id = path.split('/')[2];
                const body = await this.parseBody(req);
                
                // Mock Reviewer Identity (In real app, extracted from JWT)
                const reviewer: IdentityContext = {
                    userId: req.headers['x-user-id'] as string || 'human_reviewer',
                    orgId: 'org_default',
                    roles: ['admin', 'operator'], // Assume admin for demo
                    permissions: [],
                    auditTraceId: crypto.randomUUID()
                };

                const result = await this.reviewManager.submitDecision(
                    id, 
                    reviewer, 
                    body.decision, 
                    body.comments, 
                    body.modification
                );
                this.sendJson(res, 200, result);
                return;
            }

            // -----------------------------------------------------------------
            // MANDATORY INTROSPECTION ENDPOINTS
            // -----------------------------------------------------------------

            if (path === '/introspect' && req.method === 'GET') {
                this.sendJson(res, 200, {
                    appId: 'APP_09_Agents_HumanInLoopInterface',
                    status: 'HEALTHY',
                    metrics: {
                        activeWorkflows: 0, // TODO: Implement real counters
                        pendingReviews: this.reviewManager.getPendingReviews().length
                    },
                    config: {
                        riskThreshold: CONFIG.riskThreshold,
                        autoApproveConfidence: CONFIG.autoApproveConfidence
                    }
                });
                return;
            }

            if (path === '/assumptions' && req.method === 'GET') {
                this.sendJson(res, 200, {
                    assumptions: [
                        "Agents provide honest confidence scores.",
                        "Network latency to AI vendors is < 500ms.",
                        "Human reviewers are available within 24 hours.",
                        "Identity headers are trusted (behind gateway)."
                    ]
                });
                return;
            }

            if (path === '/failure-modes' && req.method === 'GET') {
                this.sendJson(res, 200, {
                    modes: [
                        {
                            scenario: "AI Vendor Outage",
                            impact: "Risk analysis fails; workflows default to PAUSED_FOR_REVIEW (fail-safe).",
                            mitigation: "Circuit breaker pattern implemented."
                        },
                        {
                            scenario: "Review Queue Overflow",
                            impact: "Workflows stall indefinitely.",
                            mitigation: "Alerts sent to PagerDuty when queue > 100."
                        }
                    ]
                });
                return;
            }

            if (path === '/agent-metadata' && req.method === 'GET') {
                this.sendJson(res, 200, {
                    agent_metadata: {
                        purpose: "Orchestrate human review for low-confidence or high-risk agent actions.",
                        dependencies: ["OpenAI", "Anthropic", "IdentityService"],
                        invalidation_conditions: ["Schema version mismatch", "Auth token expiry"],
                        adjacent_apps: ["APP_01_Inference_CostRouter", "APP_37_Governance_AuditTrailEngine"]
                    }
                });
                return;
            }

            this.sendJson(res, 404, { error: 'Not Found' });

        } catch (err: any) {
            Logger.log('error', 'Request failed', { error: err.message, stack: err.stack });
            this.sendJson(res, 500, { error: 'Internal Server Error', details: err.message });
        }
    }

    private parseBody(req: http.IncomingMessage): Promise<any> {
        return new Promise((resolve, reject) => {
            let body = '';
            req.on('data', chunk => body += chunk);
            req.on('end', () => {
                try {
                    resolve(JSON.parse(body));
                } catch (e) {
                    reject(e);
                }
            });
        });
    }

    private sendJson(res: http.ServerResponse, status: number, data: any) {
        res.writeHead(status, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify(data, null, 2));
    }
}

