@app.post("/v1/sources", status_code=201, response_model=SourceConfig)
async def create_source(
    config: SourceConfig,
    request: Request,
    principal: Dict[str, Any] = Depends(get_current_principal)
):
    """
    Configure and activate a new market data source.
    - **Revenue Surface**: Charged per active source, per message, and/or per enrichment call.
    - **Enterprise Upsell**: Higher throughput, more source types, advanced AI enrichment models.
    """
    try:
        manager: DataSourceManager = request.app.state.source_manager
        await manager.add_source(config)
        return config
    except (ValueError, NotImplementedError) as e:
        raise HTTPException(status_code=400, detail=str(e))
    except PermissionError as e:
        raise HTTPException(status_code=403, detail=str(e))
    except Exception as e:
        logger.error(f"Failed to create source: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail="Internal server error while creating source.")

