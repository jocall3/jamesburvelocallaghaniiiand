class CostTracker:
    """Tracks the operational costs of data ingestion and enrichment."""
    def __init__(self):
        self.total_cost = 0.0
        self.messages_processed = 0
        self.enrichment_costs = {}

    @instrument
    def record_ingestion(self, num_messages: int = 1):
        self.messages_processed += num_messages
        # A base cost could be added here for compute/network if desired

    @instrument
    def record_enrichment(self, provider: AIProvider, tokens: int = 0, invocations: int = 0):
        cost = 0.0
        if provider == AIProvider.OPENAI:
            cost = tokens * settings.cost_per_openai_token_sentiment
        elif provider == AIProvider.ANTHROPIC:
            cost = tokens * settings.cost_per_anthropic_token_sentiment
        elif provider == AIProvider.AWS_BEDROCK:
            cost = invocations * settings.cost_per_bedrock_invocation_anomaly
        
        self.total_cost += cost
        self.enrichment_costs[provider] = self.enrichment_costs.get(provider, 0.0) + cost
        logger.info(f"Cost recorded for {provider}: ${cost:.8f}. Total cost: ${self.total_cost:.8f}")

    def get_metrics(self) -> Dict[str, Any]:
        return {
            "total_cost_usd": self.total_cost,
            "total_messages_processed": self.messages_processed,
            "average_cost_per_message": self.total_cost / self.messages_processed if self.messages_processed > 0 else 0,
            "enrichment_cost_breakdown": self.enrichment_costs
        }

cost_tracker = CostTracker()

# --- AI Enrichment Adapters ---
# This demonstrates the adapter pattern for integrating multiple AI vendors.

class BaseEnrichmentAdapter:
    def __init__(self, provider: AIProvider, session: ClientSession):
        self.provider = provider
        self.session = session

    async def enrich(self, data: MarketDataTick) -> Dict[str, Any]:
        raise NotImplementedError

class OpenAISentimentAdapter(BaseEnrichmentAdapter):
    def __init__(self, session: ClientSession):
        super().__init__(AIProvider.OPENAI, session)
        if not settings.openai_api_key:
            raise ConfigurationError("OPENAI_API_KEY is not configured.")
        self.api_key = settings.openai_api_key.get_secret_value()
        self.endpoint = "https://api.openai.com/v1/chat/completions"

    @instrument
    async def enrich(self, data: MarketDataTick) -> Optional[SentimentAnalysis]:
        if not data.related_news:
            return None
        
        prompt = f"""Analyze the sentiment of the following news headline regarding the stock {data.symbol}. 
        Classify it as 'positive', 'negative', or 'neutral' and provide a confidence score from 0.0 to 1.0.
        Headline: "{data.related_news.title}"
        Respond ONLY with a JSON object in the format {{"sentiment": "...", "score": ...}}.
        """
        
        payload = {
            "model": "gpt-3.5-turbo",
            "messages": [{"role": "user", "content": prompt}],
            "temperature": 0.1,
            "response_format": {"type": "json_object"}
        }
        headers = {"Authorization": f"Bearer {self.api_key}"}

        try:
            async with self.session.post(self.endpoint, json=payload, headers=headers) as response:
                response.raise_for_status()
                result = await response.json()
                content = json.loads(result['choices'][0]['message']['content'])
                cost_tracker.record_enrichment(self.provider, tokens=result['usage']['total_tokens'])
                return SentimentAnalysis(
                    provider=self.provider.value,
                    sentiment=content.get('sentiment', 'unknown'),
                    score=content.get('score', 0.0)
                )
        except (ClientError, json.JSONDecodeError, KeyError) as e:
            logger.error(f"Error with OpenAI enrichment for {data.symbol}: {e}")
            return None

class BedrockAnomalyAdapter(BaseEnrichmentAdapter):
    # This is a simplified example. A real implementation would use boto3/aiobotocore
    # and likely a more complex model invocation for time-series anomaly detection.
    def __init__(self, session: ClientSession):
        super().__init__(AIProvider.AWS_BEDROCK, session)
        if not all([settings.aws_bedrock_region, settings.aws_access_key_id, settings.aws_secret_access_key]):
            raise ConfigurationError("AWS Bedrock credentials are not fully configured.")

    @instrument
    async def enrich(self, data: MarketDataTick) -> Optional[AnomalyDetectionResult]:
        # Mocking the call to a Bedrock model for anomaly detection
        # A real implementation would involve passing a window of recent data points.
        is_anomaly = (data.volume > 1_000_000 and abs(data.price - data.open_price) / data.open_price > 0.05)
        
        # Simulate cost and latency of a real call
        await asyncio.sleep(0.05) 
        cost_tracker.record_enrichment(self.provider, invocations=1)

        if is_anomaly:
            return AnomalyDetectionResult(
                provider=self.provider.value,
                is_anomaly=True,
                score=0.95,
                details=f"High volume ({data.volume}) and significant price move detected."
            )
        return AnomalyDetectionResult(provider=self.provider.value, is_anomaly=False, score=0.1)

# --- Ingestion Pipeline ---
# This class embodies the core tension: Latency vs. Enrichment.

class IngestionPipeline:
    def __init__(self, config: SourceConfig, event_bus: EventBus, http_session: ClientSession):
        self.config = config
        self.event_bus = event_bus
        self.http_session = http_session
        self.enrichers: List[BaseEnrichmentAdapter] = []
        self._setup_enrichers()

    def _setup_enrichers(self):
        if self.config.processing_mode == ProcessingMode.ENRICHMENT:
            for provider in self.config.enrichment_providers:
                if provider == AIProvider.OPENAI:
                    self.enrichers.append(OpenAISentimentAdapter(self.http_session))
                elif provider == AIProvider.AWS_BEDROCK:
                    self.enrichers.append(BedrockAnomalyAdapter(self.http_session))
                # Add other providers like Anthropic here
                else:
                    logger.warning(f"Enrichment provider '{provider}' not implemented.")

    @instrument
    async def process(self, raw_data: Dict[str, Any]):
        """Processes a single data point through the configured pipeline."""
        start_time = time.perf_counter()
        try:
            # 1. Standardization to Core Ontology
            tick = MarketDataTick.from_provider_format(self.config.source_type.value, raw_data)
            
            # 2. Routing based on the core architectural tension
            if self.config.processing_mode == ProcessingMode.LATENCY:
                await self._fast_path(tick)
            elif self.config.processing_mode == ProcessingMode.ENRICHMENT:
                await self._enrichment_path(tick)

            cost_tracker.record_ingestion()
            processed_message_counter.labels(
                source_type=self.config.source_type.value, 
                mode=self.config.processing_mode.value
            ).inc()

        except Exception as e:
            logger.error(f"Error processing message for source {self.config.source_id}: {e}", exc_info=True)
        finally:
            latency = time.perf_counter() - start_time
            processing_latency_histogram.labels(
                source_type=self.config.source_type.value,
                mode=self.config.processing_mode.value
            ).observe(latency)

    async def _fast_path(self, tick: MarketDataTick):
        """Low-latency path: standardize and publish immediately."""
        event = Event(
            event_id=f"evt_{uuid.uuid4().hex}",
            event_type="market.data.tick.raw",
            source_app=settings.app_name,
            data=tick.model_dump()
        )
        await self.event_bus.publish("raw_market_data", event)
        logger.debug(f"Fast path: Published raw tick for {tick.symbol}")

    async def _enrichment_path(self, tick: MarketDataTick):
        """High-enrichment path: apply AI models before publishing."""
        enriched_data = EnrichedMarketData(tick_data=tick)
        
        enrichment_tasks = [enricher.enrich(tick) for enricher in self.enrichers]
        results = await asyncio.gather(*enrichment_tasks)

        for result in results:
            if isinstance(result, SentimentAnalysis):
                enriched_data.sentiment = result
            elif isinstance(result, AnomalyDetectionResult):
                enriched_data.anomaly_detection = result
        
        event = Event(
            event_id=f"evt_{uuid.uuid4().hex}",
            event_type="market.data.tick.enriched",
            source_app=settings.app_name,
            data=enriched_data.model_dump()
        )
        await self.event_bus.publish("enriched_market_data", event)
        logger.debug(f"Enrichment path: Published enriched data for {tick.symbol}")


