# Extensible connectors for different market data providers.

class BaseSourceConnector:
    def __init__(self, config: SourceConfig, pipeline: IngestionPipeline):
        self.config = config
        self.pipeline = pipeline
        self._task: Optional[asyncio.Task] = None

    async def start(self):
        if self._task is None or self._task.done():
            self._task = asyncio.create_task(self._run())
            logger.info(f"Started connector for source {self.config.source_id}")

    async def stop(self):
        if self._task and not self._task.done():
            self._task.cancel()
            try:
                await self._task
            except asyncio.CancelledError:
                pass
            logger.info(f"Stopped connector for source {self.config.source_id}")
        self._task = None

    async def _run(self):
        raise NotImplementedError

    def is_running(self) -> bool:
        return self._task is not None and not self._task.done()

class MockStreamConnector(BaseSourceConnector):
    """A mock connector for testing and demonstration."""
    async def _run(self):
        import random
        base_prices = {symbol: random.uniform(100, 500) for symbol in self.config.symbols}
        news_headlines = [
            "Announces record profits for Q3",
            "Faces new regulatory scrutiny",
            "Launches innovative new product line",
            "CEO unexpectedly resigns",
            "Downgraded by major analyst firm"
        ]
        
        while True:
            try:
                for symbol in self.config.symbols:
                    price = base_prices[symbol] * (1 + random.uniform(-0.01, 0.01))
                    base_prices[symbol] = price
                    volume = random.randint(1000, 5000000)
                    
                    mock_tick = {
                        "ev": "T",
                        "sym": symbol,
                        "p": round(price, 2),
                        "s": random.randint(1, 100),
                        "t": int(time.time() * 1000),
                        "o": round(price * (1 + random.uniform(-0.005, 0.005)), 2),
                        "v": volume,
                        "news": {
                            "title": f"{symbol} {random.choice(news_headlines)}"
                        } if random.random() > 0.8 else None
                    }
                    await self.pipeline.process(mock_tick)
                await asyncio.sleep(1) # Simulate real-time feed
            except asyncio.CancelledError:
                logger.info(f"Mock stream for {self.config.source_id} cancelled.")
                break
            except Exception as e:
                logger.error(f"Error in mock stream for {self.config.source_id}: {e}", exc_info=True)
                await asyncio.sleep(5) # Backoff on error

# --- Source Management ---

class DataSourceManager:
    def __init__(self, event_bus: EventBus, http_session: ClientSession):
        self.event_bus = event_bus
        self.http_session = http_session
        self.feature_flags = get_feature_flag_client()

    async def add_source(self, config: SourceConfig) -> str:
        if config.source_id in ACTIVE_SOURCES:
            raise ValueError(f"Source with ID {config.source_id} already exists.")

        # Enterprise Upsell Path: Check feature flags for advanced features
        if config.processing_mode == ProcessingMode.ENRICHMENT and not self.feature_flags.is_enabled("advanced-enrichment"):
            raise PermissionError("AI Enrichment is an enterprise feature. Please upgrade your plan.")
        
        # Jurisdictional Control Example
        if config.jurisdiction and self.feature_flags.is_enabled(f"geo-block-{config.jurisdiction.lower()}"):
             raise PermissionError(f"Data ingestion from jurisdiction '{config.jurisdiction}' is restricted.")

        pipeline = IngestionPipeline(config, self.event_bus, self.http_session)
        
        connector: BaseSourceConnector
        if config.source_type == DataSourceType.MOCK_STREAM:
            connector = MockStreamConnector(config, pipeline)
        # Add other connectors like Polygon.io here
        # elif config.source_type == DataSourceType.POLYGON_STOCKS:
        #     connector = PolygonConnector(config, pipeline)
        else:
            raise NotImplementedError(f"Source type {config.source_type} not supported.")

        if config.is_active:
            await connector.start()

        ACTIVE_SOURCES[config.source_id] = {"config": config, "connector": connector}
        log_audit_event("source.added", {"source_id": config.source_id, "config": config.model_dump()})
        return config.source_id

    async def remove_source(self, source_id: str):
        if source_id not in ACTIVE_SOURCES:
            raise ValueError(f"Source with ID {source_id} not found.")
        
        source_info = ACTIVE_SOURCES.pop(source_id)
        await source_info["connector"].stop()
        log_audit_event("source.removed", {"source_id": source_id})

    def get_source_status(self, source_id: str) -> Dict[str, Any]:
        if source_id not in ACTIVE_SOURCES:
            raise ValueError(f"Source with ID {source_id} not found.")
        
        source_info = ACTIVE_SOURCES[source_id]
        return {
            "config": source_info["config"].model_dump(),
            "is_running": source_info["connector"].is_running()
        }

    def list_sources(self) -> List[Dict[str, Any]]:
        return [self.get_source_status(sid) for sid in ACTIVE_SOURCES.keys()]

    async def shutdown(self):
        logger.info("Shutting down all active source connectors...")
        tasks = [info["connector"].stop() for info in ACTIVE_SOURCES.values()]
        await asyncio.gather(*tasks)
        ACTIVE_SOURCES.clear()
        logger.info("All connectors stopped.")


# --- FastAPI Application Setup ---

@asynccontextmanager
async def lifespan(app: FastAPI):
    # Startup
    logger.info("Starting APP_11_Data_MarketFeedIngestor...")
    
    # Setup shared resources
    app.state.http_session = ClientSession()
    app.state.event_bus = EventBus() # Connects to Kafka/NATS via core_sdk
    await app.state.event_bus.connect()
    
    app.state.source_manager = DataSourceManager(app.state.event_bus, app.state.http_session)
    
    setup_metrics(app, service_name=settings.app_name)
    logger.info("Service started successfully.")
    
    yield
    
    # Shutdown
    logger.info("Shutting down service...")
    await app.state.source_manager.shutdown()
    await app.state.event_bus.disconnect()
    await app.state.http_session.close()
    logger.info("Service shutdown complete.")

app = FastAPI(
    title="APP_11_Data_MarketFeedIngestor",
    description="Ingests and enriches real-time market data feeds.",
    version="1.0.0",
    lifespan=lifespan,
    dependencies=[Depends(APISecurity())] # Apply shared auth model
)

