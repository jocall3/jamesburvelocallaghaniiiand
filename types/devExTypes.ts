// --- Prompt Management (APP_125_DevEx_PromptVersionControl, APP_126_DevEx_PromptCompiler) ---

/**
 * Represents the core content of a prompt template.
 */
export interface PromptContent {
  template: string;
  variables?: Record<string, string>; // Expected variables in the template
  description?: string;
}

/**
 * Metadata associated with a specific version of a prompt.
 */
export interface PromptVersionMetadata {
  version: string; // Semantic versioning (e.g., "1.0.0") or hash
  author: string;
  timestamp: string; // ISO 8601 date string
  commitMessage?: string;
  tags?: string[]; // e.g., ["production", "experiment-A"]
  parentVersionId?: string; // For tracking lineage
}

/**
 * A complete prompt template with its content and version metadata.
 */
export interface PromptTemplate {
  id: string; // Unique identifier for the prompt template (e.g., "summarize-document")
  name: string;
  latestVersionId?: string; // ID of the latest active version
  versions: PromptVersion[];
}

/**
 * A specific, immutable version of a prompt template.
 */
export interface PromptVersion {
  versionId: string; // Unique ID for this specific version (e.g., hash of content + metadata)
  templateId: string; // Reference to the parent PromptTemplate
  content: PromptContent;
  metadata: PromptVersionMetadata;
}

/**
 * Configuration for compiling a prompt for a specific vendor.
 */
export interface PromptCompilerConfig {
  targetVendor: string; // e.g., "openai", "anthropic", "huggingface"
  modelName?: string; // Specific model to target (e.g., "gpt-4", "claude-3-opus")
  optimizationStrategy?: 'cost' | 'latency' | 'accuracy';
  temperature?: number;
  maxTokens?: number;
  stopSequences?: string[];
  // Add other vendor-specific parameters as needed
  [key: string]: any;
}

/**
 * The payload generated by the prompt compiler, ready for a specific LLM API.
 */
export interface CompiledPromptPayload {
  vendor: string;
  model: string;
  payload: Record<string, any>; // The actual API request body
  compiledAt: string; // ISO 8601 date string
  sourcePromptVersionId: string; // Reference to the prompt version used
}

// --- A/B Testing (APP_127_DevEx_A_B_TestingFramework) ---

/**
 * Defines a single variant in an A/B test.
 */
export interface ExperimentVariant {
  id: string; // Unique ID for the variant (e.g., "control", "variant-A")
  name: string;
  description?: string;
  // Configuration specific to this variant (e.g., prompt version ID, model config, feature flag state)
  config: Record<string, any>;
}

/**
 * Configuration for an A/B test experiment.
 */
export interface ExperimentConfiguration {
  experimentId: string;
  name: string;
  description?: string;
  status: 'draft' | 'running' | 'completed' | 'paused';
  startDate: string; // ISO 8601 date string
  endDate?: string; // ISO 8601 date string
  variants: ExperimentVariant[];
  trafficAllocation: Record<string, number>; // e.g., { "control": 0.5, "variant-A": 0.5 }
  targetAudience?: Record<string, any>; // Criteria for who sees the experiment
  primaryMetric: string; // Key of the metric to optimize for
  secondaryMetrics?: string[];
  createdBy: string;
  createdAt: string; // ISO 8601 date string
}

/**
 * Represents a single data point or aggregated result from an A/B test.
 */
export interface ExperimentResult {
  experimentId: string;
  variantId: string;
  timestamp: string; // ISO 8601 date string
  metricName: string;
  value: number;
  // Additional context like user ID, session ID, etc.
  context?: Record<string, any>;
}

// --- Service Discovery (APP_128_DevEx_ServiceDiscovery) ---

/**
 * Health status of a service instance.
 */
export type ServiceHealthStatus = 'UP' | 'DOWN' | 'DEGRADED' | 'UNKNOWN';

/**
 * Details about a running instance of a service.
 */
export interface ServiceInstance {
  instanceId: string; // Unique ID for this specific running instance
  serviceName: string;
  host: string;
  port: number;
  protocol?: 'http' | 'https' | 'grpc' | 'tcp';
  healthStatus: ServiceHealthStatus;
  lastHeartbeat: string; // ISO 8601 date string
  metadata?: Record<string, string>; // e.g., region, environment, version
}

/**
 * Definition of a service type, including its capabilities and endpoints.
 */
export interface ServiceDefinition {
  serviceName: string;
  description?: string;
  apiEndpoints?: {
    path: string;
    method: 'GET' | 'POST' | 'PUT' | 'DELETE' | 'PATCH';
    description?: string;
    authRequired?: boolean;
    // OpenAPI/Swagger-like schema reference could go here
  }[];
  capabilities?: string[]; // e.g., ["LLM_inference", "data_storage", "image_generation"]
  ownerTeam?: string;
  documentationUrl?: string;
}

/**
 * A combined entry in the service registry.
 */
export interface ServiceRegistryEntry {
  definition: ServiceDefinition;
  activeInstances: ServiceInstance[];
}

// --- CI/CD Orchestration (APP_129_DevEx_CI_CD_Orchestrator) ---

/**
 * Type of a CI/CD pipeline step.
 */
export type PipelineStepType = 'build' | 'test' | 'deploy' | 'scan' | 'notify' | 'custom';

/**
 * Represents a single step or stage in a CI/CD pipeline.
 */
export interface PipelineStep {
  name: string;
  type: PipelineStepType;
  command?: string | string[]; // Command to execute
  image?: string; // Docker image for the step
  environment?: Record<string, string>;
  dependsOn?: string[]; // Names of steps this step depends on
  timeoutSeconds?: number;
  // Add more specific configurations for different step types
}

/**
 * Definition of a CI/CD pipeline.
 */
export interface PipelineDefinition {
  pipelineId: string;
  name: string;
  description?: string;
  trigger: 'manual' | 'push' | 'schedule' | 'webhook';
  repositoryUrl?: string; // For 'push' triggers
  branchFilter?: string;
  stages: PipelineStep[][]; // Stages are arrays of steps that can run in parallel
  notificationChannels?: string[]; // e.g., "slack:#dev-alerts"
  createdBy: string;
  createdAt: string; // ISO 8601 date string
}

/**
 * Status of a specific CI/CD pipeline run.
 */
export type PipelineRunStatus = 'pending' | 'running' | 'success' | 'failed' | 'cancelled';
export type StepRunStatus = 'pending' | 'running' | 'success' | 'failed' | 'skipped';

export interface PipelineStepRun {
  stepName: string;
  status: StepRunStatus;
  startTime?: string; // ISO 8601 date string
  endTime?: string; // ISO 8601 date string
  logsUrl?: string;
  errorMessage?: string;
}

export interface PipelineRun {
  runId: string;
  pipelineId: string;
  status: PipelineRunStatus;
  triggerer: string; // User or system that triggered the run
  startTime: string; // ISO 8601 date string
  endTime?: string; // ISO 8601 date string
  commitHash?: string; // For runs triggered by code pushes
  stageRuns: {
    stageName: string;
    steps: PipelineStepRun[];
  }[];
  artifacts?: {
    name: string;
    url: string;
  }[];
}

// --- Observability (APP_130_Obs_TraceabilityExplorer, APP_131_Obs_LogAggregator, APP_132_Obs_MetricsCollector, APP_133_Obs_ErrorCategorizer) ---

/**
 * Represents a single operation within a distributed trace.
 */
export interface TraceSpan {
  traceId: string;
  spanId: string;
  parentSpanId?: string;
  serviceName: string;
  operationName: string;
  startTime: string; // ISO 8601 date string
  endTime: string; // ISO 8601 date string
  durationMs: number;
  status: 'ok' | 'error';
  tags?: Record<string, string | number | boolean>; // Key-value pairs for filtering/context
  logs?: LogEntry[]; // Logs associated with this span
  // For agent-specific traces:
  agentId?: string;
  toolUsed?: string;
  input?: string;
  output?: string;
}

/**
 * A complete distributed trace, composed of multiple spans.
 */
export interface DistributedTrace {
  traceId: string;
  rootSpan: TraceSpan;
  spans: TraceSpan[]; // All spans belonging to this trace
  serviceGraph?: {
    source: string;
    target: string;
    count: number;
  }[]; // Simplified service dependency graph
}

/**
 * Represents a single log entry.
 */
export interface LogEntry {
  timestamp: string; // ISO 8601 date string
  level: 'DEBUG' | 'INFO' | 'WARN' | 'ERROR' | 'FATAL';
  serviceName: string;
  message: string;
  traceId?: string;
  spanId?: string;
  resourceId?: string; // e.g., pod name, instance ID
  context?: Record<string, any>; // Structured log data
}

/**
 * Type of metric.
 */
export enum MetricType {
  Counter = 'counter',
  Gauge = 'gauge',
  Histogram = 'histogram',
  Summary = 'summary',
}

/**
 * Key-value pairs representing metric labels/dimensions.
 */
export interface MetricLabels {
  [key: string]: string;
}

/**
 * A single data point for a metric.
 */
export interface MetricSample {
  metricName: string;
  type: MetricType;
  labels: MetricLabels;
  value: number;
  timestamp: string; // ISO 8601 date string
  // For Histogram/Summary, additional fields like sum, count, buckets
  bucket?: number; // For histogram buckets
}

