import { NetworkMonitor, NetworkStatus, NetworkMetrics } from '../../domain/network/NetworkMonitor';
import { Logger } from '../../infrastructure/logging/Logger';
import { SystemHealthRepository } from '../../domain/system/SystemHealthRepository';
import { UseCase } from '../UseCase';

/**
 * Configuration for the Network Health Monitoring Use Case.
 */
interface MonitorNetworkHealthConfig {
    /** Interval in milliseconds between health checks. */
    checkIntervalMs: number;
    /** Threshold for latency (ms) to consider the network degraded. */
    latencyThresholdMs: number;
    /** Threshold for packet loss (%) to consider the network degraded. */
    packetLossThresholdPercent: number;
}

/**
 * Use Case for continuously monitoring the health and performance of the entire network.
 * This involves periodic checks for latency, packet loss, and overall connectivity.
 */
export class MonitorNetworkHealthUseCase implements UseCase<void, Promise<void>> {
    private readonly monitor: NetworkMonitor;
    private readonly repository: SystemHealthRepository;
    private readonly logger: Logger;
    private readonly config: MonitorNetworkHealthConfig;
    private intervalId: NodeJS.Timeout | null = null;
    private isRunning: boolean = false;

    constructor(
        monitor: NetworkMonitor,
        repository: SystemHealthRepository,
        logger: Logger,
        config: MonitorNetworkHealthConfig
    ) {
        this.monitor = monitor;
        this.repository = repository;
        this.logger = logger.child('MonitorNetworkHealthUseCase');
        this.config = config;
    }

    /**
     * Starts the continuous network health monitoring loop.
     * @returns A promise that resolves when the monitoring process is stopped externally.
     */
    public async execute(): Promise<void> {
        if (this.isRunning) {
            this.logger.warn('Monitoring is already running.');
            return;
        }

        this.isRunning = true;
        this.logger.info(`Starting network health monitoring every ${this.config.checkIntervalMs}ms.`);

        // Initial check immediately upon starting
        await this.performHealthCheck();

        // Set up the recurring interval
        this.intervalId = setInterval(() => {
            this.performHealthCheck().catch(err => {
                this.logger.error('Error during scheduled network health check:', err);
            });
        }, this.config.checkIntervalMs);

        // Return a promise that never resolves, simulating a long-running background process
        return new Promise<void>(() => {
            // The process is managed by external stop() call or process termination
        });
    }

    /**
     * Stops the continuous network health monitoring loop.
     */
    public stop(): void {
        if (this.intervalId) {
            clearInterval(this.intervalId);
            this.intervalId = null;
            this.isRunning = false;
            this.logger.info('Network health monitoring stopped.');
        }
    }

    /**
     * Performs a single network health check and updates the system repository.
     */
    private async performHealthCheck(): Promise<void> {
        try {
            this.logger.debug('Executing network health check...');
            const metrics: NetworkMetrics = await this.monitor.checkHealth();
            
            const status: NetworkStatus = this.determineStatus(metrics);
            
            await this.repository.updateNetworkHealth({
                timestamp: new Date(),
                status: status,
                metrics: metrics,
            });

            this.logStatus(status, metrics);

        } catch (error) {
            this.logger.error('Failed to retrieve network metrics:', error);
            // Optionally, report a critical failure status if monitoring itself fails
            await this.repository.updateNetworkHealth({
                timestamp: new Date(),
                status: 'CRITICAL_MONITOR_FAILURE',
                metrics: { latencyMs: -1, packetLossPercent: 100, successRate: 0 },
            });
        }
    }

    /**
     * Determines the overall network status based on collected metrics and configured thresholds.
     */
    private determineStatus(metrics: NetworkMetrics): NetworkStatus {
        if (metrics.latencyMs > this.config.latencyThresholdMs) {
            this.logger.warn(`Latency (${metrics.latencyMs}ms) exceeds threshold (${this.config.latencyThresholdMs}ms).`);
            return 'DEGRADED_LATENCY';
        }
        if (metrics.packetLossPercent > this.config.packetLossThresholdPercent) {
            this.logger.warn(`Packet loss (${metrics.packetLossPercent}%) exceeds threshold (${this.config.packetLossThresholdPercent}%).`);
            return 'DEGRADED_PACKET_LOSS';
        }
        
        // Assuming successRate is derived from 1 - packetLossPercent, or directly measured
        if (metrics.successRate < 0.95) {
             this.logger.warn(`Success rate (${metrics.successRate}) is low.`);
             return 'WARNING';
        }

        return 'OPERATIONAL';
    }

    private logStatus(status: NetworkStatus, metrics: NetworkMetrics): void {
        switch (status) {
            case 'OPERATIONAL':
                this.logger.debug(`Network operational. Latency: ${metrics.latencyMs.toFixed(1)}ms, Loss: ${metrics.packetLossPercent.toFixed(2)}%`);
                break;
            case 'DEGRADED_LATENCY':
            case 'DEGRADED_PACKET_LOSS':
            case 'WARNING':
                this.logger.warn(`Network status changed to ${status}. Metrics: Latency=${metrics.latencyMs.toFixed(1)}ms, Loss=${metrics.packetLossPercent.toFixed(2)}%`);
                break;
            case 'CRITICAL_MONITOR_FAILURE':
                this.logger.error('Network status is CRITICAL due to monitoring failure.');
                break;
        }
    }
}
