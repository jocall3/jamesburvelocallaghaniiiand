/**
 * @file AlertRepository.ts
 * @description This file contains the repository for persisting and managing fraud alerts.
 * It uses Prisma as the ORM to interact with the underlying database.
 */

import { PrismaClient, Alert, AlertStatus, AlertSeverity, Prisma } from '@prisma/client';
import { injectable, inject } from 'tsyringe';

/**
 * Represents the criteria for querying alerts.
 * All properties are optional, allowing for flexible filtering.
 */
export interface FindAlertsCriteria {
  status?: AlertStatus;
  severity?: AlertSeverity;
  transactionId?: string;
  ruleId?: string;
  assigneeId?: string | null;
  dateFrom?: Date;
  dateTo?: Date;
}

/**
 * Represents the pagination options for querying alerts.
 */
export interface PaginationOptions {
  limit?: number;
  offset?: number;
}

/**
 * Represents the data required to create a new alert.
 * It omits fields that are auto-generated by the database.
 */
export type CreateAlertData = Omit<Alert, 'id' | 'createdAt' | 'updatedAt'>;

/**
 * Represents the data that can be used to update an existing alert.
 */
export type UpdateAlertData = Partial<Omit<Alert, 'id' | 'createdAt' | 'updatedAt'>>;

/**
 * @interface IAlertRepository
 * @description Defines the contract for the alert repository, abstracting the data persistence layer.
 * This allows for different implementations (e.g., in-memory for tests, different DBs)
 * without changing the application's business logic.
 */
export interface IAlertRepository {
  /**
   * Creates a new fraud alert in the database.
   * @param data - The data for the new alert.
   * @returns A promise that resolves to the newly created alert.
   */
  create(data: CreateAlertData): Promise<Alert>;

  /**
   * Finds a single alert by its unique identifier.
   * @param id - The unique ID of the alert.
   * @returns A promise that resolves to the found alert or null if not found.
   */
  findById(id: string): Promise<Alert | null>;

  /**
   * Finds all alerts that match the given criteria, with pagination.
   * @param criteria - The filtering criteria.
   * @param pagination - The pagination options (limit, offset).
   * @returns A promise that resolves to an array of alerts.
   */
  find(criteria: FindAlertsCriteria, pagination?: PaginationOptions): Promise<Alert[]>;

  /**
   * Updates an existing alert.
   * @param id - The ID of the alert to update.
   * @param data - The data to update the alert with.
   * @returns A promise that resolves to the updated alert or null if not found.
   */
  update(id: string, data: UpdateAlertData): Promise<Alert | null>;

  /**
   * Counts the number of alerts that match the given criteria.
   * @param criteria - The filtering criteria.
   * @returns A promise that resolves to the total count of matching alerts.
   */
  count(criteria: FindAlertsCriteria): Promise<number>;
}

/**
 * @class AlertRepository
 * @implements {IAlertRepository}
 * @description A Prisma-based implementation of the IAlertRepository.
 * It handles all database operations related to fraud alerts.
 */
@injectable()
export class AlertRepository implements IAlertRepository {
  /**
   * Creates an instance of AlertRepository.
   * @param prisma - The PrismaClient instance, injected via DI.
   */
  constructor(@inject('PrismaClient') private readonly prisma: PrismaClient) {}

  /**
   * @inheritdoc
   */
  async create(data: CreateAlertData): Promise<Alert> {
    try {
      const alert = await this.prisma.alert.create({
        data,
      });
      return alert;
    } catch (error) {
      // In a real application, you'd have a more sophisticated logging and error handling mechanism.
      console.error('Failed to create alert:', error);
      if (error instanceof Prisma.PrismaClientKnownRequestError) {
        // Handle specific Prisma errors if necessary
      }
      throw new Error('Database error: Could not create alert.');
    }
  }

  /**
   * @inheritdoc
   */
  async findById(id: string): Promise<Alert | null> {
    try {
      return await this.prisma.alert.findUnique({
        where: { id },
      });
    } catch (error) {
      console.error(`Failed to find alert with id ${id}:`, error);
      throw new Error('Database error: Could not retrieve alert.');
    }
  }

  /**
   * @inheritdoc
   */
  async find(criteria: FindAlertsCriteria, pagination: PaginationOptions = {}): Promise<Alert[]> {
    const { limit, offset } = pagination;
    const where = this.buildWhereClause(criteria);

    try {
      return await this.prisma.alert.findMany({
        where,
        take: limit,
        skip: offset,
        orderBy: {
          createdAt: 'desc', // Default sorting: newest first
        },
      });
    } catch (error) {
      console.error('Failed to find alerts:', error);
      throw new Error('Database error: Could not retrieve alerts.');
    }
  }

  /**
   * @inheritdoc
   */
  async update(id: string, data: UpdateAlertData): Promise<Alert | null> {
    try {
      return await this.prisma.alert.update({
        where: { id },
        data,
      });
    } catch (error) {
      if (error instanceof Prisma.PrismaClientKnownRequestError && error.code === 'P2025') {
        // P2025 is the error code for "Record to update not found."
        return null;
      }
      console.error(`Failed to update alert with id ${id}:`, error);
      throw new Error('Database error: Could not update alert.');
    }
  }

  /**
   * @inheritdoc
   */
  async count(criteria: FindAlertsCriteria): Promise<number> {
    const where = this.buildWhereClause(criteria);
    try {
      return await this.prisma.alert.count({ where });
    } catch (error) {
      console.error('Failed to count alerts:', error);
      throw new Error('Database error: Could not count alerts.');
    }
  }

  /**
   * A private helper method to construct the Prisma `where` clause from the search criteria.
   * @param criteria - The filtering criteria for alerts.
   * @returns A `Prisma.AlertWhereInput` object for Prisma queries.
   */
  private buildWhereClause(criteria: FindAlertsCriteria): Prisma.AlertWhereInput {
    const where: Prisma.AlertWhereInput = {};

    if (criteria.status) {
      where.status = criteria.status;
    }
    if (criteria.severity) {
      where.severity = criteria.severity;
    }
    if (criteria.transactionId) {
      where.transactionId = criteria.transactionId;
    }
    if (criteria.ruleId) {
      where.ruleId = criteria.ruleId;
    }
    if (criteria.assigneeId !== undefined) {
      where.assigneeId = criteria.assigneeId;
    }
    if (criteria.dateFrom || criteria.dateTo) {
      where.createdAt = {};
      if (criteria.dateFrom) {
        where.createdAt.gte = criteria.dateFrom;
      }
      if (criteria.dateTo) {
        where.createdAt.lte = criteria.dateTo;
      }
    }

    return where;
  }
}