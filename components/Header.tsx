function universeReducer(state: UniverseState, action: UniverseAction): UniverseState {
    switch (action.type) {
        case 'SET_ACTIVE_VIEW':
            return { ...state, activeView: action.payload };
        case 'ADD_NOTIFICATION':
            const newNotification: Notification = {
                ...action.payload,
                id: `notif_${Date.now()}_${Math.random()}`,
                timestamp: new Date().toISOString(),
                read: false,
            };
            return {
                ...state,
                notifications: [newNotification, ...state.notifications.slice(0, 99)],
            };
        case 'MARK_NOTIFICATION_READ':
            return {
                ...state,
                notifications: state.notifications.map(n =>
                    n.id === action.payload ? { ...n, read: true } : n
                ),
            };
        case 'DISMISS_ALL_NOTIFICATIONS':
            return {
                ...state,
                notifications: state.notifications.map(n => ({ ...n, read: true })),
            };
        case 'TICK_UNIVERSE':
            const newTime = state.globalTime + 1;
            return {
                ...state,
                globalTime: newTime,
                kernel: {
                    ...state.kernel,
                    cpuUsage: 10 + Math.sin(newTime / 30) * 5 + Math.random() * 5,
                    memoryUsage: 25 + Math.cos(newTime / 50) * 10 + Math.random() * 3,
                    activeThreads: 250 + Math.floor(Math.sin(newTime / 15) * 20),
                },
            };
        case 'UPDATE_API_STATE':
            return {
                ...state,
                apiEcosystem: {
                    ...state.apiEcosystem,
                    [action.payload.id]: {
                        ...state.apiEcosystem[action.payload.id],
                        ...action.payload.state,
                        lastActivity: new Date().toISOString(),
                    },
                },
            };
        case 'UPDATE_HEURISTIC_ENGINE_STATUS':
            return {
                ...state,
                heuristicEngine: {
                    ...state.heuristicEngine,
                    ...action.payload,
                },
            };
        case 'SET_API_EXPLORER_SELECTION':
            return {
                ...state,
                apiExplorer: {
                    selectedApiId: action.payload,
                    endpointResponse: null,
                    isLoading: false,
                }
            };
        case 'SET_API_EXPLORER_RESPONSE':
            return {
                ...state,
                apiExplorer: {
                    ...state.apiExplorer,
                    endpointResponse: action.payload.response,
                    isLoading: action.payload.isLoading,
                }
            };
        default:
            return state;
    }
}

export const UniverseContext = createContext<UniverseContextType | null>(null);

const useUniverse = (): UniverseContextType => {
    const context = useContext(UniverseContext);
    if (!context) {
        throw new Error("useUniverse must be used within a UniverseProvider");
    }
    return context;
};


