/**
 * A custom hook for detecting clicks outside a component.
 */
const useOutsideClick = (ref: React.RefObject<any>, callback: () => void) => {
    useEffect(() => {
        const handleClickOutside = (event: MouseEvent) => {
            if (ref.current && !ref.current.contains(event.target)) {
                callback();
            }
        };
        document.addEventListener("mousedown", handleClickOutside);
        return () => {
            document.removeEventListener("mousedown", handleClickOutside);
        };
    }, [ref, callback]);
};

/**
 * A generic dropdown component.
 */
const Dropdown: React.FC<{
    trigger: React.ReactNode;
    children: React.ReactNode;
    isOpen: boolean;
    setIsOpen: (isOpen: boolean) => void;
    className?: string;
}> = ({ trigger, children, isOpen, setIsOpen, className }) => {
    const dropdownRef = useRef(null);
    useOutsideClick(dropdownRef, () => setIsOpen(false));

    return (
        <div className="relative" ref={dropdownRef}>
            <div onClick={() => setIsOpen(!isOpen)}>{trigger}</div>
            {isOpen && (
                <div className={`absolute right-0 mt-2 bg-gray-800 border border-gray-700 rounded-lg shadow-lg z-50 ${className}`}>
                    {children}
                </div>
            )}
        </div>
    );
};


