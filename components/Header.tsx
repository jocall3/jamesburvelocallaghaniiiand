// This is the core of the simulated universe. Each API is a mini-application.

type ApiEndpoint = (params: any, dataStore: any) => Promise<any>;

class APISimulator {
    public state: SimulatedAPIState;
    private dataStore: any;
    private endpoints: Record<string, ApiEndpoint>;
    private lastTick: number;

    constructor(id: string, name: string, initialDataStore: any, endpoints: Record<string, ApiEndpoint>) {
        this.state = {
            id,
            name,
            status: 'initializing',
            uptime: 0,
            requestsPerSecond: 0,
            errorRate: 0,
            latency: 20,
            dataStoreSizeBytes: JSON.stringify(initialDataStore).length,
            lastActivity: new Date().toISOString(),
        };
        this.dataStore = initialDataStore;
        this.endpoints = endpoints;
        this.lastTick = Date.now();

        setTimeout(() => { this.state.status = 'online'; }, Math.random() * 2000 + 500);
    }

    public tick(dispatch: React.Dispatch<UniverseAction>) {
        const now = Date.now();
        const delta = (now - this.lastTick) / 1000;
        this.lastTick = now;

        if (this.state.status !== 'offline') {
            this.state.uptime += delta;
        }

        // Simulate status changes
        if (Math.random() < 0.0005) {
            this.state.status = this.state.status === 'online' ? 'degraded' : 'online';
        }
        if (Math.random() < 0.0001) {
            this.state.status = 'offline';
            setTimeout(() => { this.state.status = 'online'; }, 20000 + Math.random() * 20000);
        }

        // Simulate load
        this.state.requestsPerSecond = Math.max(0, this.state.requestsPerSecond + (Math.random() - 0.5) * 5);
        this.state.latency = Math.max(10, 20 + this.state.requestsPerSecond * 0.5 + (Math.random() - 0.5) * 10);
        this.state.errorRate = this.state.status === 'degraded' ? Math.min(100, 5 + Math.random() * 10) : Math.max(0, this.state.errorRate + (Math.random() - 0.5) * 0.2);
        
        this.state.dataStoreSizeBytes = JSON.stringify(this.dataStore).length;

        dispatch({ type: 'UPDATE_API_STATE', payload: { id: this.state.id, state: { ...this.state } } });
    }

    public async call(endpoint: string, params: any): Promise<any> {
        if (this.state.status === 'offline') {
            throw new Error('API is offline');
        }
        if (!this.endpoints[endpoint]) {
            throw new Error('Endpoint not found');
        }
        if (Math.random() * 100 < this.state.errorRate) {
            throw new Error('Simulated API Error');
        }

        this.state.requestsPerSecond += 1;
        const startTime = Date.now();
        const result = await this.endpoints[endpoint](params, this.dataStore);
        const callLatency = Date.now() - startTime;
        this.state.latency = (this.state.latency * 9 + callLatency) / 10; // Moving average
        return result;
    }
}

