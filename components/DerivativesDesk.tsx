/**
 * @class BaseAPISimulator
 * Provides common functionality for all simulated APIs, including
 * authentication, rate limiting, and basic error handling.
 */
abstract class BaseAPISimulator {
  protected _datastore: any;
  protected _config: { apiKey: string; rateLimit: number; currentRequests: number; lastReset: number; name: string };

  constructor(name: string, initialData: any = {}) {
    this._config = { apiKey: `${name.toUpperCase()}_DEV_KEY_${Math.random().toString(36).substr(2, 5)}`, rateLimit: 100, currentRequests: 0, lastReset: Date.now(), name };
    this._datastore = initialData;
  }

  protected _checkAuth(apiKey: string): { success: boolean; error?: string } {
    if (apiKey !== this._config.apiKey) {
      return { success: false, error: 'Unauthorized: Invalid API Key' };
    }
    return { success: true };
  }

  protected _checkRateLimit(): { success: boolean; error?: string } {
    const now = Date.now();
    if (now - this._config.lastReset > 60000) { // Reset every minute
      this._config.currentRequests = 0;
      this._config.lastReset = now;
    }
    if (this._config.currentRequests >= this._config.rateLimit) {
      return { success: false, error: `Rate limit exceeded for ${this._config.name}. Try again in ${Math.ceil((60000 - (now - this._config.lastReset)) / 1000)} seconds.` };
    }
    this._config.currentRequests++;
    return { success: true };
  }

  protected _handleRequest(apiKey: string, callback: () => { success: boolean; data?: any; error?: string }): { success: boolean; data?: any; error?: string } {
    const authResult = this._checkAuth(apiKey);
    if (!authResult.success) return authResult;
    const rateLimitResult = this._checkRateLimit();
    if (!rateLimitResult.success) return rateLimitResult;
    try {
      return callback();
    } catch (e: any) {
      return { success: false, error: `Internal API Error in ${this._config.name}: ${e.message}` };
    }
  }
}

