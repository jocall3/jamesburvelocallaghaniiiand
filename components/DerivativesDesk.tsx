/**
 * @interface Position
 * Represents a single financial position held by the desk. Expanded to include
 * more granular details and risk parameters.
 */
interface Position {
  id: string; // Changed to string for UUID-like generation
  type: 'Call' | 'Put' | 'Future' | 'Swap' | 'StructuredProduct' | 'ExoticOption' | 'VarianceSwap';
  asset: string; // Underlying asset identifier (e.g., 'SPX_FUT', 'AAPL_EQ', 'BTC_USD')
  strike: number | null; // Strike price for options, null for futures/swaps
  expiry: string; // ISO Date string (e.g., '2024-09-30T16:00:00Z')
  premium: number; // Price paid/received for the derivative
  quantity: number; // Number of contracts/units
  isLong: boolean; // True for long position, false for short
  iv: number; // Implied Volatility (Explicit Stability - a core theme)
  delta: number; // First-order sensitivity to underlying price
  gamma: number; // Second-order sensitivity to underlying price
  theta: number; // Sensitivity to time decay
  vega: number; // Sensitivity to implied volatility
  rho: number; // Sensitivity to interest rates
  lambda: number; // Elasticity (percentage change in option value per 1% change in underlying)
  charm: number; // Delta decay over time (dDelta/dTime)
  vanna: number; // Vega sensitivity to underlying price (dVega/dUnderlying)
  vomma: number; // Vega sensitivity to implied volatility (dVega/dIV)
  speed: number; // Third-order sensitivity to underlying price (dGamma/dUnderlying)
  zomma: number; // Gamma sensitivity to implied volatility (dGamma/dIV)
  color: number; // Gamma sensitivity to time decay (dGamma/dTime)
  epsilon: number; // Sensitivity to dividend yield
  kappa: number; // Another name for Vega, but here used for specific volatility regime sensitivity
  rho2: number; // Sensitivity to short-term interest rates (original rho for long-term)
  correlationExposure: { [key: string]: number }; // Exposure to specific asset correlations
  liquidityImpact: number; // Estimated impact on market liquidity if unwound
  counterpartyRiskScore: number; // Simulated counterparty risk score (0-100)
  collateralRequired: number; // Amount of collateral needed for this position
  entryTimestamp: string; // When the position was opened
  status: 'Open' | 'Closed' | 'Pending' | 'Expired'; // Current status of the position
}

